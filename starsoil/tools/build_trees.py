"""Compile the original complete oak artwork into compact native RGB565.

Keep the authored branches and foliage as one silhouette. Alpha thresholding
and nearest-grid sampling are asset compilation, not runtime image filtering.
"""
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
W,H=112,96
im=Image.open(ROOT/'art/trees/oak-canopy-v1.png').convert('RGBA')
alpha=im.getchannel('A').point(lambda v:255 if v>=128 else 0)
bounds=alpha.getbbox()
source=im.crop(bounds)
source=source.resize((W,H),Image.Resampling.NEAREST)
rows=list(source.getdata())
stump=[x for x in range(W) if rows[(H-3)*W+x][3]>=128]
anchor=(min(stump)+max(stump))//2
variants=[]
for biome in range(3):
 pixels=[]
 for r,g,b,a in rows:
  if a<128:pixels.append(0);continue
  if g>=r*.91 and g>b*1.08:
   if biome==1:
    lum=.35*r+.58*g+.07*b
    snow=max(0,min(1,(lum-125)/85))
    r,g,b=[int(v*(1-snow)+s*snow) for v,s in zip((lum*.47+15,lum*.66+20,lum*.79+23),(231,239,226))]
   elif biome==2:r,g,b=int(r*.82),min(255,int(g*1.02)),min(255,int(b*1.14))
  v=((r&248)<<8)|((g&252)<<3)|(b>>3)
  pixels.append(v or 1)
 variants.append(pixels)
with (ROOT/'tree_art.hpp').open('w') as out:
 out.write('// Generated by tools/build_trees.py from original imagegen artwork.\n#pragma once\n#include <cstdint>\nnamespace tree_art {\n')
 out.write(f'inline constexpr int Width={W},Height={H},Anchor={anchor};\ninline constexpr uint16_t oak[3][{W*H}]={{\n')
 for pixels in variants:out.write('{'+','.join(map(str,pixels))+'},\n')
 out.write('};\n}\n')
print(f'Compiled 3 natural canopy palettes, {W}x{H}, trunk anchor {anchor}; retained alpha and authored branch silhouette')
