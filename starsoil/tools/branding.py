SYMBOLS = (
    ('00111100','01100110','11111111','11011011','11000011','11111111','11011011','01111110'),
    ('00011000','01111100','11111110','01111110','00011000','00110000','01100000','11000000'),
    ('01100110','11111111','11011011','01111110','00111100','00111100','00111100','00111100'),
    ('11001100','11111110','10110110','10110110','10110110','10110110','11111110','01100110'),
    ('01111110','11111111','10011001','10111101','10111101','10011001','11111111','01111110'),
)


def symbols():
    output=[]
    for rows in SYMBOLS:
        im=Image.new('RGBA',(8,8));d=ImageDraw.Draw(im)
        for y,row in enumerate(rows):
            for x,c in enumerate(row):
                if c=='1':d.point((x,y),fill='#edc985' if y<3 else '#9fbdaf')
        output.append(im)
    return output
