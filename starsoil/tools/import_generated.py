#!/usr/bin/env python3
"""Import generated PNG sheets into bounded, reproducible native pixel assets.

Only technical slicing, area sampling, binary alpha and palette reduction occur
here. The source paintings and prompts live in art/generated/source.json.
"""
from pathlib import Path
import hashlib,json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'art/generated'
NAMES=('dew-slime','dusk-bat','mossling','gem-crawler','warden','frost-slime','dune-beetle','lantern-moth','thorn-hornet')
FLYING={1,7,8}

def binary(image,cutoff=160):
    image=image.convert('RGBA')
    image.putalpha(image.getchannel('A').point(lambda value:255 if value>=cutoff else 0))
    return image

def limited(images,colors):
    """One palette across all frames; transparent pixels never bias its colors."""
    opaque=[(r,g,b)for image in images for r,g,b,a in image.getdata()if a]
    sample=Image.new('RGB',(len(opaque),1));sample.putdata(opaque)
    palette=sample.quantize(colors=colors,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
    result=[]
    for image in images:
        colored=image.convert('RGB').quantize(palette=palette,dither=Image.Dither.NONE).convert('RGBA')
        colored.putalpha(image.getchannel('A'))
        colored.putdata([(r,g,b,255)if a else(0,0,0,0)for r,g,b,a in colored.getdata()])
        result.append(colored)
    return result

def native_creatures(sources):
    atlas=Image.new('RGBA',(144,216))
    for kind,name in enumerate(NAMES):
        source=Image.open(DEST/sources[name]['file']).convert('RGBA')
        assert source.width%3==0 and source.height%2==0
        width,height=source.width//3,source.height//2
        frames=[]
        for frame in range(6):
            x,y=frame%3*width,frame//3*height
            image=binary(source.crop((x,y,x+width,y+height)))
            frames.append(binary(image.resize((24,24),Image.Resampling.BOX),128))
        if kind not in FLYING:
            bottom=max(image.getbbox()[3]for image in frames)
            shifted=[]
            for image in frames:
                target=Image.new('RGBA',(24,24));target.paste(image,(0,24-bottom));shifted.append(target)
            frames=shifted
        frames=limited(frames,31)
        strip=Image.new('RGBA',(144,24))
        for frame,image in enumerate(frames):
            strip.paste(image,(frame*24,0));atlas.paste(image,(frame*24,kind*24))
        strip.save(DEST/(name+'-frames-v1.png'),optimize=True)
    atlas.save(DEST/'creature-frames-v1.png',optimize=True)
    return atlas

def native_ui(sources):
    source=Image.open(DEST/sources['ui']['file']).convert('RGBA')
    # The generated image has a 30px transparent footer, recorded explicitly.
    xs=(0,418,836,1254);ys=(0,411,810,1224)
    tiles=[]
    for row in range(3):
        for col in range(3):
            image=source.crop((xs[col],ys[row],xs[col+1],ys[row+1]))
            tiles.append(binary(image.resize((32,32),Image.Resampling.BOX),128))
    tiles=limited(tiles,63);atlas=Image.new('RGBA',(96,96))
    for i,image in enumerate(tiles):atlas.paste(image,(i%3*32,i//3*32))
    atlas.save(DEST/'ui-tiles-v1.png',optimize=True)
    # Generate indexed C++ sources; transparent index zero remains reserved.
    colors=sorted({(r>>3)<<11|(g>>2)<<5|(b>>3)for image in tiles for r,g,b,a in image.getdata()if a})
    palette=[0]+[color or 1 for color in colors]
    assert len(palette)<=64
    lookup={color:i+1 for i,color in enumerate(colors)}
    rows=[]
    for image in tiles:
        rows.append([lookup[(r>>3)<<11|(g>>2)<<5|(b>>3)]if a else 0 for r,g,b,a in image.getdata()])
    text='// SPDX-License-Identifier: MIT\n// Generated by tools/import_generated.py; source PNGs and prompts are retained.\n#pragma once\n#include <cstdint>\nnamespace starsoil_skin_art {\n'
    text+='inline constexpr uint16_t palette[64]={'+','.join(map(str,palette+[0]*(64-len(palette))))+'};\n'
    text+='inline constexpr uint8_t tiles[9][1024]={\n'+',\n'.join('{'+','.join(map(str,row))+'}'for row in rows)+'\n};\n}\n'
    (ROOT/'ui_art.hpp').write_text(text)
    return atlas

def native_title(sources):
    source=binary(Image.open(DEST/sources['title-logo']['file']))
    source=source.crop(source.getbbox())
    from PIL import ImageOps
    fitted=ImageOps.contain(source,(222,46),Image.Resampling.BOX)
    image=Image.new('RGBA',(224,48));image.paste(fitted,((224-fitted.width)//2,(48-fitted.height)//2))
    image=limited([binary(image,128)],63)[0]
    image.save(DEST/'title-logo-v1.png',optimize=True)
    colors=sorted({(r>>3)<<11|(g>>2)<<5|(b>>3)for r,g,b,a in image.getdata()if a})
    palette=[0]+[c or 1 for c in colors];lookup={c:i+1 for i,c in enumerate(colors)}
    pixels=[lookup[(r>>3)<<11|(g>>2)<<5|(b>>3)]if a else 0 for r,g,b,a in image.getdata()]
    runs=[];offsets=[0]
    for y in range(48):
        row=pixels[y*224:(y+1)*224];x=0
        while x<224:
            end=x+1
            while end<224 and row[end]==row[x]:end+=1
            runs.extend([end-x,row[x]]);x=end
        offsets.append(len(runs))
    text='// SPDX-License-Identifier: MIT\n// Generated from retained title art by tools/import_generated.py.\n#pragma once\n#include <cstdint>\nnamespace starsoil_title_art {\n'
    text+='inline constexpr uint16_t palette[64]={'+','.join(map(str,palette+[0]*(64-len(palette))))+'};\n'
    text+='inline constexpr uint16_t rows[49]={'+','.join(map(str,offsets))+'};\n'
    text+='inline constexpr uint8_t runs['+str(len(runs))+']={'+','.join(map(str,runs))+'};\n}\n'
    (ROOT/'title_art.hpp').write_text(text)

def main():
    metadata=json.loads((DEST/'source.json').read_text());sources={item['name']:item for item in metadata['sources']}
    for item in sources.values():assert hashlib.sha256((DEST/item['file']).read_bytes()).hexdigest()==item['sha256']
    native_creatures(sources);native_ui(sources)
    if 'title-logo' in sources:native_title(sources)
    print('Imported nine 6-frame 24x24 creature loops and nine 32x32 UI tiles with bounded palettes.')
if __name__=='__main__':main()
