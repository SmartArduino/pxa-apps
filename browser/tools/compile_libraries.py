#!/usr/bin/env python3
"""Compile optional, signed library assets from exact, curated local sources."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile


def require(condition, message):
    if not condition:
        raise ValueError(message)


def build(app, compiler):
    manifest = json.loads((app / 'runtime/libraries.json').read_text(encoding='utf-8'))
    require(manifest.get('format') == 'pxa-browser-script-libraries-1', 'unsupported manifest format')
    require(isinstance(manifest.get('libraries'), list), 'libraries must be an array')
    destination = app / 'assets/script-libraries'
    destination.mkdir(exist_ok=True)
    rows, files, ids, digests = [], {}, set(), set()
    # Validate every entry and compiler result before publishing any new file.
    # Stage beside the destination so atomic renames work across mount points.
    with tempfile.TemporaryDirectory(prefix='.script-libraries-', dir=destination.parent) as directory:
        temporary = Path(directory)
        for entry in manifest['libraries']:
            identity = entry['id']
            require(isinstance(identity, str) and re.fullmatch(r'[a-zA-Z0-9._-]{1,128}', identity), 'invalid library id')
            require(identity not in ids, f'duplicate library id: {identity}')
            ids.add(identity)
            source, license = (app / entry['source']).resolve(), (app / entry['license']).resolve()
            require(source.is_relative_to(app) and license.is_relative_to(app), f'{identity}: input escapes app directory')
            raw, notice = source.read_bytes(), license.read_bytes()
            require(0 < len(raw) <= 32768, f'{identity}: source must be 1..32768 bytes')
            require(notice, f'{identity}: license is empty')
            filename = entry['filename']
            require(isinstance(filename, str) and 0 < len(filename) <= 256 and '\0' not in filename,
                    f'{identity}: invalid diagnostic filename')
            digest = hashlib.sha256(raw).hexdigest()
            require(digest not in digests, f'{identity}: duplicate source identity')
            digests.add(digest)
            target = temporary / (digest + '.qjb')
            subprocess.run([str(compiler), str(source), str(target), filename], check=True)
            bytecode = target.read_bytes()
            require(8 < len(bytecode) <= 65536 and bytecode.startswith(b'PXAQJS1\n'),
                    f'{identity}: compiler produced invalid or oversized bytecode')
            files[target.name] = bytecode
            files['LICENSE.' + identity + '.txt'] = notice
            rows.append((len(raw), digest))
        rows.sort()
        header = ('// Generated by tools/compile_libraries.py. Do not edit.\n#pragma once\n'
                  '#include <array>\n#include <cstddef>\n#include <string_view>\n'
                  'namespace browser::script {\n'
                  'struct LibraryEntry {std::size_t source_bytes;std::string_view sha256;};\n'
                  f'inline constexpr std::array<LibraryEntry,{len(rows)}> compiled_libraries{{{{\n' +
                  ''.join(f'    {{{size},"{digest}"}},\n' for size, digest in rows) + '}};\n}\n')
        publications = [(destination / name, data) for name, data in files.items()]
        publications.append((app / 'browser_script_libraries.hpp', header.encode()))
        for number, (path, data) in enumerate(publications):
            if path.exists() and path.read_bytes() == data:
                continue  # A no-op regeneration must not force C++ rebuilds.
            staged = temporary / f'publish-{number}'
            staged.write_bytes(data)
            staged.replace(path)
        # This directory is generator-owned; keep unrelated files intact.
        for path in destination.iterdir():
            generated = re.fullmatch(r'[0-9a-f]{64}\.qjb|LICENSE\.[a-zA-Z0-9._-]+\.txt', path.name)
            if generated and path.name not in files:
                path.unlink()
    print(f'Compiled script library identities: {len(rows)}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('compiler', type=Path)
    args = parser.parse_args()
    try:
        build(Path(__file__).resolve().parent.parent, args.compiler.resolve(strict=True))
    except (OSError, ValueError, KeyError, TypeError, AttributeError, subprocess.CalledProcessError) as error:
        parser.exit(1, f'script libraries: {error}\n')


if __name__ == '__main__':
    main()
