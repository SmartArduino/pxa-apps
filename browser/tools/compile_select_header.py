#!/usr/bin/env python3
"""Embed the signed app's optional select bytecode; never accepts web data."""
from pathlib import Path
import sys

data=Path(sys.argv[1]).read_bytes()
if not data.startswith(b'PXAQJS1\n') or not 8<len(data)<=65536:
    raise SystemExit('Invalid app-owned select bytecode')
data=data[8:]
rows=[','.join(f'0x{v:02x}' for v in data[i:i+20])+',' for i in range(0,len(data),20)]
Path(sys.argv[2]).write_text('// Generated by tools/compile_runtime.sh; app-owned trusted bytecode.\n'
    '#pragma once\n#include <cstdint>\nnamespace browser::script::detail {\n'
    'inline constexpr std::uint8_t select_runtime[] = {\n'+ '\n'.join(rows)+'\n};\n}\n')
