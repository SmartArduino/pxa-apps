#!/usr/bin/env python3
"""Rebuild the bounded glyph atlas from SIL-OFL Noto Sans CJK (14 px)."""
from pathlib import Path
from PIL import Image, ImageFont, ImageDraw
root=Path(__file__).resolve().parents[1]
words='遗迹疾奔开始探险操作指南继续重来返回主菜单暂停旅程结束最佳纪录本次得分距离金币丛林石桥落日神庙幽蓝古墓向左转右滑动变道上跳跃下铲轻触屏幕手柄方向键音效开关画质精美流畅已准备护盾磁铁碰到障碍错过弯口坠入深渊冒险者收集全部累计帮助退出米新穿越守卫按任意确认关闭设置选择'
words+=''.join(c for path in root.glob('*.cpp') for c in path.read_text() if ord(c)>127)
chars=''.join(dict.fromkeys(''.join(chr(i) for i in range(32,127))+words))
assert len(chars)<=512
font=ImageFont.truetype('/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc',14)
im=Image.new('L',(256,512));d=ImageDraw.Draw(im);adv=[]
for i,c in enumerate(chars):
    x=(i%16)*16;y=(i//16)*16
    d.text((x,y-3),c,font=font,fill=255,stroke_width=0)
    adv.append(round(font.getlength(c)))
data=list(im.get_flattened_data());extra_height=max(0,((len(chars)-256+15)//16)*16)
with (root/'font_data.hpp').open('w') as f:
    f.write('// Generated by tools/build_font.py; glyph outlines: Noto Sans CJK, SIL OFL 1.1.\n#pragma once\n#include <cstdint>\nnamespace relic::font {\n')
    f.write('inline constexpr uint32_t codes[] = {'+','.join(str(ord(c)) for c in chars)+'};\n')
    f.write('inline constexpr uint8_t advance[] = {'+','.join(map(str,adv))+'};\n')
    f.write('inline constexpr uint8_t atlas[65536] = {\n')
    for i in range(0,65536,256):f.write(','.join(map(str,data[i:i+256]))+',\n')
    f.write('};\ninline constexpr uint16_t extra_height='+str(extra_height)+';\n')
    f.write('inline constexpr uint8_t atlas_extra['+str(max(1,256*extra_height))+']={'+','.join(map(str,data[65536:65536+256*extra_height] or [0]))+'};\n')
    large=Image.new('L',(128,36));ld=ImageDraw.Draw(large)
    titlefont=ImageFont.truetype('/usr/share/fonts/noto-cjk/NotoSerifCJK-Bold.ttc',28)
    for i,c in enumerate('遗迹疾奔'):ld.text((i*32, -5),c,font=titlefont,fill=255)
    f.write('inline constexpr uint8_t title_atlas[4608]={'+','.join(map(str,large.get_flattened_data()))+'};\n}\n')
print(f'{len(chars)} glyphs; 65536 atlas bytes')

# Keep the signed binary distribution's notices in sync with embedded glyphs.
from runpy import run_path
run_path(str(root / 'tools/build_notices.py'), run_name='__main__')
