#!/usr/bin/env python3
"""Original 64 px stone, moss, wood and carved-jade material tiles. No imported artwork.
The generated atlas and palette are source assets, not screenshots.
"""
from pathlib import Path
import math,random
root=Path(__file__).resolve().parents[1]
# In a staging directory, generate next to this script.
if not (root/'core.hpp').exists():root=Path(__file__).resolve().parent
rng=random.Random(0x52454c49)
colors=[0]*256
ramps=[((56,72,70),(178,186,169)),((29,61,42),(124,149,77)),((55,34,25),(180,126,70)),((27,68,64),(137,175,141))]
for tile,(low,high) in enumerate(ramps):
 for i in range(48):
  a=i/47;rgb=[round(l*(1-a)+h*a) for l,h in zip(low,high)]
  colors[16+tile*48+i]=(rgb[0]>>3)<<11|(rgb[1]>>2)<<5|(rgb[2]>>3)
for i in range(16):
 a=i/15;rgb=[round(l*(1-a)+h*a)for l,h in zip((94,65,27),(239,201,116))]
 colors[224+i]=(rgb[0]>>3)<<11|(rgb[1]>>2)<<5|(rgb[2]>>3)
colors[1]=65535
pixels=[0]*16384
for tile in range(4):
 for y in range(64):
  for x in range(64):
   noise=rng.uniform(-.45,.45);value=31+noise;palette_tile=0
   if tile in (0,1):
    edge=min(x,y,63-x,63-y)
    value+=.7*math.sin(x*.12+y*.08)
    if edge<1:value=8
    elif edge<3:value=39 if x<32 or y<32 else 22
    # Short edge fissures and small moss clusters leave the slab centre quiet.
    crack=abs(x-(53+int(2*math.sin(y*.23))))
    if 7<y<25 and crack<.7:value=19
    if tile==1 and ((x<17 and y<14+4*math.sin(x*.35)) or (x>51 and y>53)):
     palette_tile=1;value=18+9*math.sin(x*.27)*math.cos(y*.23)
   elif tile==2:
    palette_tile=2;value=26+5*math.sin(x*.5+math.sin(y*.1)*.5)+noise
    if x%20<1:value-=7
   else:
    palette_tile=3;value=26+noise
    dx=x-31.5;dy=y-31.5;r=math.hypot(dx,dy);a=math.atan2(dy,dx)
    if 23<r<25 or abs(r-(6+(a+math.pi)*2.2))<1.4:
     value=12+int(noise*2);palette_tile=None
    elif 26<r<28:value=9
   value=max(0,min(47,round(value)))
   px=x+(tile%2)*64;py=y+(tile//2)*64
   pixels[py*128+px]=(224+min(15,value)) if palette_tile is None else (16+48*palette_tile+value)
p=root/'material_data.hpp'
with p.open('w') as f:
 f.write('// Generated by tools/build_materials.py; original MIT-licensed artwork.\n#pragma once\n#include <cstdint>\nnamespace relic::materials {\n')
 f.write('inline constexpr uint16_t palette[256]={'+','.join(map(str,colors))+'};\n')
 f.write('inline constexpr uint8_t atlas[16384]={\n')
 for at in range(0,len(pixels),128):f.write(','.join(map(str,pixels[at:at+128]))+',\n')
 f.write('};\n}\n')
print(p)
