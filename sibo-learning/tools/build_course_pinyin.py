"""Build compact, text-checked annotations from existing public course metadata.

--fixtures contains index.json and <poem-id>-meta.json downloaded from
https://wtoy.doit.am/oss/shici/. No network or synthesis runs during a build.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import unicodedata

app = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--fixtures', type=Path, required=True)
p.add_argument('--output', type=Path, default=app / 'course_pinyin.inc')
p.add_argument('--report', type=Path, required=True)
a = p.parse_args()
course = json.loads(re.search(r'R"JSON\((.*)\)JSON"', (app / 'course.inc').read_text(), re.S)[1])
poems = {entry['id']: entry for entry in course}
index = json.loads((a.fixtures / 'index.json').read_text())
rows, report = [], []
for entry in sorted(index, key=lambda value: value['id']):
    poem = poems[entry['id']]
    assert entry['listen'] == f"poems/{entry['id']}/listen.mp3"
    assert entry['follow'] == f"poems/{entry['id']}/follow.mp3"
    raw = (a.fixtures / (entry['id'] + '-meta.json')).read_bytes()
    data = json.loads(raw)
    cells = [cell for line in data['pinyin'] for cell in line['items']]
    assert ''.join(cell['char'] for cell in cells) == ''.join(poem['lines']), entry['id']
    tokens = []
    for cell in cells:
        assert len(cell['char']) == 1
        py = unicodedata.normalize('NFC', cell['pinyin'])
        assert len(py.encode()) <= 32 and (py or not '\u3400' <= cell['char'] <= '\u9fff')
        assert not any(c.isspace() or c in '"\\' for c in py)
        tokens.append(py or '-')
    hashed = 2166136261
    for byte in '\n'.join(poem['lines']).encode():
        hashed = ((hashed ^ byte) * 16777619) & 0xffffffff
    rows.append(f'  {{"{entry["id"]}", 0x{hashed:08x}u, "{" ".join(tokens)}"}},')
    report.append({'id': entry['id'], 'title': poem['title'], 'characters': len(cells),
                   'metadata_sha256': hashlib.sha256(raw).hexdigest()})
assert len(rows) == len(set(entry['id'] for entry in index))
a.output.parent.mkdir(parents=True, exist_ok=True)
a.output.write_text('// SPDX-License-Identifier: MIT\n'
    '// Public course annotations: https://wtoy.doit.am/oss/shici/index.json\n'
    '// Generated by tools/build_course_pinyin.py; tokens follow original UTF-8 characters.\n'
    'struct OfflinePinyin { const char *id; uint32_t body_hash; const char *tokens; };\n'
    'static constexpr OfflinePinyin kOfflinePinyin[] = {\n' + '\n'.join(rows) + '\n};\n')
a.report.parent.mkdir(parents=True, exist_ok=True)
a.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
print(f'{len(rows)} poems; {a.output.stat().st_size} source bytes; text checked against offline originals')
