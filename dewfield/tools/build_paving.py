"""Compile original native-pixel paving guided by art/reference/paving-v1.png.

No image decoding at runtime: transparent 4-bit indexed surface stamps bake
into the existing ground cache. All construction happens on this pixel grid.
"""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parents[1]
COLORS=[None,(176,168,137),(187,178,146),(181,175,145),(193,183,151),
        (168,161,133),(180,171,140),(185,177,148),(175,169,141),
        (164,156,127),(200,190,159),(190,181,148),(172,164,135),
        (180,175,143),(195,184,151),(167,161,131)]
def rgb(c):return ((c[0]&248)<<8)|((c[1]&252)<<3)|(c[2]>>3) if c else 0

def noise(x,y):
    h=(x*374761393+y*668265263+0x83aa7f19)&0xffffffff
    h=((h^(h>>13))*1274126177)&0xffffffff
    return h^(h>>16)

def plaza():
    w,h=108,100
    seeds=[]
    # Staggered sites at non-tile spacing produce fitted polygonal flags.
    for row,y in enumerate(range(2,h+10,10)):
        for col,x in enumerate(range(-8,w+12,14)):
            n=noise(col+31,row+17)
            sx=x+(7 if row%2 else 0)+int(n%7)-3
            sy=y+int((n>>8)%5)-2
            radius=((sx-54)/51)**2+((sy-49)/47)**2
            if radius<.96 or (radius<1.18 and n%4==0):seeds.append((sx,sy,n))
    owners=[]
    for y in range(h):
        for x in range(w):
            distances=sorted(((x-sx)**2+int((y-sy)**2*1.5),i) for i,(sx,sy,_) in enumerate(seeds))
            d,i=distances[0]
            # Outer cells end in a worn irregular ellipse, with small fragments
            # near its edge rather than a rectangular tile-atlas boundary.
            radius=((x-54)/53)**2+((y-49)/48)**2
            owners.append(i if radius<1.0 and d<95 else -1)
    pixels=[0]*(w*h)
    for y in range(1,h-1):
        for x in range(1,w-1):
            i=owners[y*w+x]
            if i<0:continue
            # One-pixel dirt joints, on one side only (no thick black outlines).
            if owners[y*w+x+1]!=i or owners[(y+1)*w+x]!=i:continue
            sx,sy,n=seeds[i];c=1+(n%7)
            # Small quiet clusters, avoiding white rims or cast shadows.
            if noise(x//3,y//2)%19==0:c=13
            if n%9==0 and x==sx+1 and sy-2<=y<=sy+1:c=8
            pixels[y*w+x]=c
    return w,h,pixels

# Stepped asymmetric outlines, widths vary along every silhouette. The last
# row is still the top face; there is no offset skirt or ground shadow.
PROFILES=[
 [(3,9),(1,12),(0,14),(0,15),(1,14),(1,13),(3,11),(5,8)],
 [(2,7),(0,10),(0,11),(0,11),(1,10),(2,8)],
 [(4,8),(2,12),(0,15),(0,16),(1,16),(1,15),(3,12),(5,9),(7,5)],
 [(2,4),(0,7),(0,8),(1,7),(2,5)],
 [(4,11),(2,15),(0,18),(0,19),(1,19),(1,18),(3,15),(5,11),(7,7)],
 [(2,6),(0,10),(0,12),(1,12),(2,11),(3,9),(5,6)],
]
def stone(kind):
    rows=PROFILES[kind];w=max(x+n for x,n in rows);h=len(rows);p=[0]*(w*h)
    for y,(start,length) in enumerate(rows):
        for x in range(start,start+length):
            c=2 if kind%3 else 3
            if noise(x//3+kind*7,y//2)%13==0:c=7
            if kind in (2,4) and x==w//2+y//3 and 2<=y<h-2:c=8
            p[y*w+x]=c
    return w,h,p

def emit():
    images=[('Plaza',plaza())]+[(f'Stone{i}',stone(i)) for i in range(len(PROFILES))]
    lines=['// SPDX-License-Identifier: MIT','// Generated by tools/build_paving.py. Original stepped pixel surfaces; see art/reference/paving-v1.json.','#pragma once','#include <cstdint>','namespace paving_sprites {','struct Image {uint8_t w,h;const uint8_t*indices;};',
           'inline constexpr uint16_t Palette[]={'+','.join(str(rgb(c)) for c in COLORS)+'};']
    size=32
    for name,(w,h,pixels) in images:
        if len(pixels)%2:pixels.append(0)
        data=[pixels[i]|(pixels[i+1]<<4) for i in range(0,len(pixels),2)]
        lines.append('inline constexpr uint8_t '+name+'Data[]={'+','.join(map(str,data))+'};')
        lines.append(f'inline constexpr Image {name}={{{w},{h},{name}Data}};');size+=len(data)
    lines+=['inline constexpr const Image*Stones[]={'+','.join('&Stone'+str(i) for i in range(len(PROFILES)))+'};','} // namespace paving_sprites']
    (ROOT/'paving_sprites.hpp').write_text('\n'.join(lines)+'\n')
    print(f'Compiled {len(images)} ground stamps: {size} bytes; 16 colours; no extra frame buffer')
    return images
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--preview',type=Path);args=p.parse_args();images=emit()
    if args.preview:
        from PIL import Image
        im=Image.new('RGB',(180,112),(212,173,107));ox=0;oy=6
        for name,(w,h,pixels) in images:
            if name!='Plaza':ox=118;oy=6+int(name[5:])*16
            for y in range(h):
                for x in range(w):
                    c=pixels[y*w+x]
                    if c:im.putpixel((ox+x,oy+y),COLORS[c])
        args.preview.parent.mkdir(parents=True,exist_ok=True);im.resize((720,448),Image.Resampling.NEAREST).save(args.preview)
