#!/usr/bin/env python3
"""Compile original sword pixels, registered grip/tip and exact mirror poses."""
from pathlib import Path
from PIL import Image,ImageDraw
import math,json
from build_sprites import compile_sprite
root=Path(__file__).resolve().parents[1]
im=Image.new('RGBA',(44,44));d=ImageDraw.Draw(im);ink=(65,54,39,255)
d.polygon([(22,5),(24,9),(24,18),(20,18),(20,9)],fill=ink)
d.polygon([(22,6),(23,10),(23,18),(21,18),(21,10)],fill=(173,195,187,255));d.line((22,7,22,17),fill=(239,237,204,255))
d.rectangle((18,18,26,20),fill=ink);d.rectangle((19,18,25,19),fill=(199,148,67,255));d.rectangle((21,20,23,25),fill=ink);d.line((22,20,22,24),fill=(155,107,65,255));d.rectangle((21,25,23,26),fill=(205,160,78,255))
with (root/'mine_sprites.hpp').open('w') as f:
 f.write('// SPDX-License-Identifier: MIT\n// Generated by tools/build_mine_sword.py.\n#pragma once\n#include "pixel_sprite.hpp"\nnamespace sprites {\n')
 compile_sprite(f,'mine_sword_icon',im.crop((15,3,30,28)))
 for mirror in [False,True]:
  items=[]
  for angle in range(16):
   a=(-angle if mirror else angle)*math.pi/8;pose=im.rotate(-a*180/math.pi,resample=Image.Resampling.NEAREST,center=(22.5,22.5))
   if mirror:
    flipped=pose.transpose(Image.Transpose.FLIP_LEFT_RIGHT);pose=Image.new('RGBA',(44,44));pose.paste(flipped,(1,0))
   def point(px,py):
    dx,dy=px-22,py-22;x=round(dx*math.cos(a)-dy*math.sin(a));y=round(dx*math.sin(a)+dy*math.cos(a));return (-x if mirror else x),y
   key=f'held_sword_{"m" if mirror else "n"}{angle}';compile_sprite(f,key,pose)
   geometry=(*point(22,6),*point(22,24),*point(22,6));items.append('{&'+key+','+','.join(map(str,geometry))+'}')
  f.write('inline constexpr HeldFrame sword_'+('mirrors' if mirror else 'frames')+'[]={'+','.join(items)+'};\n')
 f.write('}\n')
im.save(root/'art/world-v2/sword.png')
(root/'art/world-v2/sword.json').write_text(json.dumps({'tool':'tools/build_mine_sword.py','license':'MIT','grip':[22,22],'tip':[22,6],'angles':16,'horizontal_mirrors':True},indent=2)+'\n')
