#!/usr/bin/env python3
"""Bake deterministic connected cave rooms into 30 x 24 occupancy bit rows."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def noise(seed,x,y):
 h=(seed^(x*374761393&0xffffffff)^(y*668265263&0xffffffff))&0xffffffff;h=((h^(h>>13))*1274126177)&0xffffffff;return h^(h>>16)
def floor(depth,x,y):
 if x<2 or x>29 or y<2 or y>21:return False
 if x==16 and 2<=y<=16:return True
 if y in (7,16) and 7<=x<=25:return True
 if x in (7,25) and 7<=y<=16:return True
 # Rounded irregular chambers keep all ore, mob and forage anchors connected.
 return any((x-cx)**2*16+(y-cy)**2*16 <= (4+(noise(depth,cx,cy)&1))**2*16-((noise(depth,x,y)%3)*6) for cy in (7,16) for cx in (7,16,25))
rows=[[sum(1<<x for x in range(32) if floor(depth,x,y))for y in range(24)]for depth in range(1,31)]
(root/'mine_layouts.hpp').write_text('// SPDX-License-Identifier: MIT\n// Generated by tools/build_mine_layouts.py. One bit per traversable tile.\n#pragma once\n#include <cstdint>\nnamespace farm {\ninline constexpr uint32_t MineFloorRows[30][24]={\n'+',\n'.join('{'+','.join(hex(n)+'u'for n in r)+'}'for r in rows)+'\n};\n}\n')
