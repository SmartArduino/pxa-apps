#!/usr/bin/env python3
"""Compile six distinct generated buildings to 4-bit native pixel spans."""
from pathlib import Path
from PIL import Image
import argparse
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--preview',type=Path);args=parser.parse_args()
sheet=Image.open(root/'art/reference/buildings-v3-concept.png').convert('RGBA')
# Annotated main door centres in the source cells. They register every front
# step to the actual portal, independently of an asymmetric roof or lean-to.
door_centres=[236,264,256,236,260,254]
out=['// Generated by tools/build_buildings.py from original imagegen art.\n#pragma once\n#include "pixel_sprite.hpp"\nnamespace building_sprites {\nstruct Image {sprites::Sprite shape;const uint8_t *indices;const uint16_t *palette;};\n']
images=[];total=0
for kind in range(6):
 col,row=kind%3,kind//3
 cell=sheet.crop((col*sheet.width//3,row*sheet.height//2,(col+1)*sheet.width//3,(row+1)*sheet.height//2))
 mask=cell.getchannel('A').point(lambda a:255 if a>=192 else 0)
 # The generated atlas has a few neighbouring-cell fringe pixels. Extract the
 # connected building silhouette rather than registering a stray leaf as eave.
 mw,mh=mask.size;bits=bytearray(mask.tobytes());largest=[]
 for at in range(len(bits)):
  if not bits[at]:continue
  bits[at]=0;component=[at];head=0
  while head<len(component):
   q=component[head];head+=1;xx,yy=q%mw,q//mw
   for dy in (-1,0,1):
    for dx in (-1,0,1):
     nx,ny=xx+dx,yy+dy
     if not(0<=nx<mw and 0<=ny<mh):continue
     n=ny*mw+nx
     if bits[n]:bits[n]=0;component.append(n)
  if len(component)>len(largest):largest=component
 clean=bytearray(mw*mh)
 for at in largest:clean[at]=255
 mask=Image.frombytes('L',(mw,mh),bytes(clean));cell.putalpha(mask);box=mask.getbbox();assert box
 x0,y0,x1,y1=box;scale=84/(x1-x0);height=round((y1-y0)*scale);assert height<=100
 image=cell.crop(box).resize((84,height),Image.Resampling.NEAREST)
 alpha=image.getchannel('A').point(lambda a:255 if a>=192 else 0)
 indexed=image.convert('RGB').quantize(colors=16,dither=Image.Dither.NONE)
 palette=indexed.getpalette();colors=[((palette[i]&248)<<8)|((palette[i+1]&252)<<3)|(palette[i+2]>>3)for i in range(0,48,3)]
 runs=[];values=[];pixels=indexed.load();opaque=alpha.load()
 for y in range(height):
  x=0
  while x<84:
   if not opaque[x,y]:x+=1;continue
   first=x;offset=len(values)
   while x<84 and opaque[x,y]:values.append(pixels[x,y]);x+=1
   runs.append((y,first,x-first,offset))
 packed=[(values[i]&15)|((values[i+1]if i+1<len(values)else 0)<<4)for i in range(0,len(values),2)]
 # Contact derives from the actual lowest opaque pixel, never a floating oval.
 points={}
 for x in range(84):
  y=next((y for y in range(height-1,max(-1,height-11),-1)if opaque[x,y]),None)
  if y is None:continue
  for xx,yy,a in ((x,y+1,2),(x-1,y+1,1),(x+1,y+1,1),(x,y+2,1)):
   if 0<=xx<84 and 0<=yy<height and opaque[xx,yy]:continue
   points[xx,yy]=max(a,points.get((xx,yy),0))
 contacts=[]
 for y in sorted({y for x,y in points}):
  xs=sorted(x for x,yy in points if yy==y);i=0
  while i<len(xs):
   x=xs[i];a=points[x,y];end=x+1;i+=1
   while i<len(xs)and xs[i]==end and points[xs[i],y]==a:end+=1;i+=1
   contacts.append((y,x,end-x,a))
 key=f'b{kind}';anchor=round((door_centres[kind]-x0)*scale)
 out += [f'inline constexpr uint16_t {key}_palette[]={{'+','.join(map(str,colors))+'};\n',
  f'inline constexpr uint8_t {key}_pixels[]={{'+','.join(map(str,packed))+'};\n',
  f'inline constexpr sprites::Span {key}_spans[]={{'+','.join('{'+','.join(map(str,r))+'}'for r in runs)+'};\n',
  f'inline constexpr sprites::ShadowSpan {key}_contacts[]={{'+','.join('{'+','.join(map(str,r))+'}'for r in contacts)+'};\n',
  f'inline constexpr sprites::Shadow {key}_shadow={{{len(contacts)},{key}_contacts}};\n',
  f'inline constexpr Image {key}={{{{84,{height},{len(runs)},{key}_spans,nullptr,{anchor},{height},&{key}_shadow}},{key}_pixels,{key}_palette}};\n']
 im=indexed.convert('RGBA');im.putalpha(alpha);images.append(im)
 total+=len(packed)+len(runs)*6+len(contacts)*4+32
 print(f'{kind}: 84x{height}, door={anchor}, opaque={len(values)}, bytes={len(packed)+len(runs)*6}')
out+=['inline constexpr const Image *Images[]={&b0,&b1,&b2,&b3,&b4,&b5};\n}\n']
(root/'building_sprites.hpp').write_text(''.join(out));print('total bytes',total)
if args.preview:
 preview=Image.new('RGBA',(6*100,104))
 for i,im in enumerate(images):preview.paste(im,(i*100+8,100-im.height),im)
 preview.resize((1800,312),Image.Resampling.NEAREST).save(args.preview)
