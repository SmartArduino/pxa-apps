#!/usr/bin/env python3
"""Author original native pixel animals and compile mirrored walking poses.

No resampling, image decoding or runtime rotation is used by the game.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageOps
import json
ROOT=Path(__file__).resolve().parents[1]
INK=(84,65,46,255);CREAM=(243,224,173,255);SHADE=(184,160,110,255)

def animal(kind,stage,frame):
    im=Image.new('RGBA',(32,28));d=ImageDraw.Draw(im)
    # Each age is authored separately: chicks/down, lanky juveniles, full adults.
    w=([8,12,15] if kind<2 else [13,20,26])[stage]
    h=([8,11,14] if kind<2 else [10,15,19])[stage]
    left=(32-w)//2;right=left+w-1;bottom=26;top=bottom-h
    def box(a,c):
        if a[2]>=a[0] and a[3]>=a[1]:d.rectangle(a,fill=c)
    def poly(p,c):d.polygon(p,fill=c)
    def oval(b,c):d.ellipse(b,fill=c)
    body=(231,212,163,255) if kind==0 else (174,162,112,255) if kind==1 else CREAM if kind==2 else (231,218,177,255) if kind==3 else (211,155,122,255)
    light=tuple(min(255,c+15) for c in body[:3])+(255,)
    dark=tuple(max(0,c-40) for c in body[:3])+(255,)
    if kind<2:
        if stage==0:body=(232,191,84,255);light=(250,221,132,255);dark=(188,143,66,255)
        foot=(185,117,48,255)
        for x in [left+w//3,right-3]:
            dx=(frame if x==left+w//3 else -frame)
            box((x+dx,bottom-2,x+dx,bottom-1),foot);box((x+dx,bottom,x+dx+2,bottom),INK)
        oval((left,top+3,right-1,bottom-3),INK)
        oval((left+1,top+4,right-2,bottom-4),body)
        # Duck's neck, broad bill and slate wing differ from a hen's round crop.
        hx=right-3;hy=top+(0 if kind==0 else 1)
        box((hx-2,hy+3,hx+1,bottom-6),body)
        oval((hx-3,hy,hx+2,hy+6),INK);oval((hx-2,hy+1,hx+1,hy+5),light)
        box((hx+2,hy+3,hx+(4 if kind==1 else 3),hy+4),(215,151,57,255))
        d.point((hx+1,hy+2),fill=INK)
        if stage>0:
            poly([(left+2,top+5),(left+6,top+6),(left+4,bottom-4),(left+1,bottom-6)],dark)
            d.line((left+2,top+6,left+4,top+7),fill=light)
            if kind==0:box((hx-1,hy-1,hx,hy),(181,83,54,255))
        poly([(left+1,top+5),(left-2,top+3),(left-1,top+8)],body)
    else:
        # Four grounded legs. Opposite pairs alternate while the torso stays level.
        for n,x in enumerate([left+3,left+6,right-6,right-3]):
            dx=frame if n in (0,3) else -frame
            box((x+dx,bottom-6,x+dx+1,bottom),INK)
            box((x+dx,bottom-5,x+dx,bottom-1),dark if n%2 else body)
        oval((left,top+2,right-3,bottom-3),INK)
        oval((left+1,top+3,right-4,bottom-4),body)
        d.line((left+4,top+3,right-7,top+3),fill=light)
        if kind==2:
            for x,y in [(left+5,top+5),(left+11,top+8),(right-9,top+4)]:
                poly([(x,y),(x+3,y-1),(x+4,y+2),(x+1,y+3)],(105,92,64,255))
            if stage==2:box((right-10,bottom-4,right-6,bottom-2),(207,149,117,255))
        if kind==3:
            # Distinct scalloped wool silhouette, rather than a resized cow.
            for x in range(left+3,right-5,4):
                oval((x-2,top,x+3,top+5),INK);oval((x-1,top+1,x+2,top+4),light)
            for x in range(left+2,right-5,4):d.line((x,top+8,x+2,top+7),fill=SHADE)
        hx=right-4;hy=top+(3 if kind==4 else 1)
        oval((hx-2,hy,right+1,hy+(7 if stage==0 else 10)),INK)
        oval((hx-1,hy+1,right,hy+(6 if stage==0 else 9)),body if kind!=3 else SHADE)
        poly([(hx-2,hy+1),(hx-4,hy-1),(hx-4,hy+3)],dark)
        poly([(right-1,hy+1),(right+1,hy-1),(right+1,hy+3)],light)
        d.point((right-1,hy+3),fill=INK);d.point((right-2,hy+3),fill=INK)
        if kind==4:
            oval((right-1,hy+5,right+3,hy+8),INK);box((right,hy+6,right+2,hy+7),(224,164,132,255));d.point((right+1,hy+6),fill=INK)
            d.arc((left-3,top+5,left+1,top+9),20,300,fill=INK)
        else:
            box((right-1,hy+6,right+1,hy+8),dark)
            d.line((left,top+5,left-1,bottom-5),fill=INK)
            if stage==2:d.line((hx,hy,hx-1,hy-2),fill=CREAM)
    return im

def main():
    rows=[];sheet=Image.new('RGBA',(3*32,5*28))
    out=ROOT/'animal_sprites.hpp'
    with out.open('w') as f:
        f.write('// SPDX-License-Identifier: MIT\n// Generated by tools/build_livestock.py; native integer pixels.\n#pragma once\n#include "pixel_sprite.hpp"\nnamespace animal_sprites {\nusing sprites::Sprite;using sprites::Span;\n')
        for kind in range(5):
            ages=[]
            for stage in range(3):
                sheet.paste(animal(kind,stage,0),(stage*32,kind*28));poses=[]
                for heading in range(2):
                    for frame in range(2):
                        im=animal(kind,stage,frame)
                        if heading:im=ImageOps.mirror(im)
                        name=f'a{kind}_{stage}_{heading}_{frame}';runs=[];colors=[]
                        for y in range(28):
                            x=0
                            while x<32:
                                if not im.getpixel((x,y))[3]:x+=1;continue
                                start=x;offset=len(colors)
                                while x<32 and im.getpixel((x,y))[3]:
                                    r,g,b,a=im.getpixel((x,y));colors.append(((r&248)<<8)|((g&252)<<3)|(b>>3));x+=1
                                runs.append((y,start,x-start,offset))
                        f.write(f'inline constexpr uint16_t {name}_pixels[]={{'+','.join(map(str,colors))+'};\n')
                        f.write(f'inline constexpr Span {name}_spans[]={{'+','.join('{'+','.join(map(str,r))+'}' for r in runs)+'};\n')
                        f.write(f'inline constexpr Sprite {name}={{32,28,{len(runs)},{name}_spans,{name}_pixels,16,27,nullptr}};\n')
                        poses.append('&'+name)
                ages.append('{'+','.join(poses)+'}')
            rows.append('{'+','.join(ages)+'}')
        f.write('inline constexpr const Sprite *animals[5][3][4]={'+','.join(rows)+'};\n}\n')
    path=ROOT/'art/world-v2/livestock.png';sheet.save(path)
    (path.with_suffix('.json')).write_text(json.dumps({'tool':'tools/build_livestock.py','license':'MIT','layout':'chicken, duck, cow, sheep, pig; baby / juvenile / adult','native_size':[32,28],'runtime':'RGB565 spans, two leg poses and true east/west mirrors'},indent=2)+'\n')

if __name__=='__main__':main()
