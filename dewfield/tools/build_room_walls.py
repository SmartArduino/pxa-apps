"""Compile the approved room concept into tiny nearest-neighbor wall materials."""
from pathlib import Path
import hashlib,json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'art/reference/home-rooms-v1.png'
SLICES={
 'BeamH':((65,28,329,61),(64,8)),
 'BeamV':((549,65,585,321),(8,64)),
 'Post':((546,24,587,68),(12,12)),
 'Collar':((549,343,585,375),(10,8)),
 'Jamb':((585,535,612,633),(8,28)),
 'Plaster':((73,69,229,115),(40,12)),
 'Skirting':((801,608,1065,633),(64,6)),
 'Window':((239,68,376,160),(34,23)),
 'Door':((600,1008,732,1164),(32,38)),
 'Mat':((614,945,718,993),(26,12)),
}
def rgb565(c):return ((c[0]&248)<<8)|((c[1]&252)<<3)|(c[2]>>3)
def main():
 source=Image.open(SOURCE).convert('RGB')
 out=['// SPDX-License-Identifier: MIT','// Generated by tools/build_room_walls.py; source: art/reference/home-rooms-v1.png.','#pragma once','#include <cstdint>','namespace room_wall_sprites {','struct Material {int w,h;const uint16_t*palette;const uint8_t*data;};']
 total=0
 for name,(box,size) in SLICES.items():
  im=source.crop(box).resize(size,Image.Resampling.NEAREST).quantize(colors=15,method=Image.Quantize.MEDIANCUT)
  palette=im.getpalette();colors=[0]+[rgb565(palette[i:i+3])for i in range(0,45,3)];indices=[i+1 for i in im.get_flattened_data()]
  if name in ('Post','Collar'):
   w,h=size
   for x,y in ((0,0),(w-1,0),(0,h-1),(w-1,h-1)):indices[y*w+x]=0
  packed=[indices[i]|((indices[i+1]if i+1<len(indices)else 0)<<4)for i in range(0,len(indices),2)]
  out.append('inline constexpr uint16_t '+name+'Colors[]={'+','.join(map(str,colors))+'};')
  out.append('inline constexpr uint8_t '+name+'Pixels[]={'+','.join(map(str,packed))+'};')
  out.append(f'inline constexpr Material {name}{{{size[0]},{size[1]},{name}Colors,{name}Pixels}};')
  total+=len(packed)+32
 out+=['constexpr uint8_t index(const Material&m,int x,int y){int p=y*m.w+x;return (m.data[p/2]>>((p&1)*4))&15;}','constexpr uint16_t sample(const Material&m,int x,int y){return m.palette[index(m,x,y)];}','}']
 (ROOT/'room_wall_sprites.hpp').write_text('\n'.join(out)+'\n')
 meta={'source':'home-rooms-v1.png','source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),'compiler':'tools/build_room_walls.py','sampling':'nearest; 15 opaque colors plus transparency per material','slices':{k:{'source_box':b,'native_size':s}for k,(b,s)in SLICES.items()},'packed_bytes_with_palettes':total}
 (ROOT/'art/reference/room-wall-materials-v1.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2)+'\n')
 print(f'{len(SLICES)} reference materials, {total} bytes including palettes')
if __name__=='__main__':main()
