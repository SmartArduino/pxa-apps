#!/usr/bin/env python3
"""Compile the generated four-view farmer to the same native limb rig."""
from pathlib import Path
from PIL import Image
import build_sprites as sprite
root=Path(__file__).resolve().parents[1]
source=Image.open(root/'art/world-v2/farmer-female-v2.png').convert('RGBA')
cells=[]
for i in range(4):
 cell=source.crop((i*source.width//4,0,(i+1)*source.width//4,source.height))
 box=cell.getchannel('A').point(lambda a:255 if a>=160 else 0).getbbox()
 assert box
 cells.append((cell,box))
# One uniform scale across all directions, registered to the hair centre and
# boot baseline. Preserve the source alpha; no painted-on hair or masks.
scale=28/(cells[0][1][3]-cells[0][1][1]);views={}
for name,(cell,(x0,y0,x1,y1)) in zip(('south','east','north','west'),cells):
 body=cell.crop((x0,y0,x1,y1));width,height=round(body.width*scale),round(body.height*scale)
 head=cell.getchannel('A').crop((x0,y0,x1,y0+round((y1-y0)*.4))).point(lambda a:255 if a>=160 else 0).getbbox()
 center=(head[0]+head[2])/2
 canvas=Image.new('RGBA',(24,32));canvas.paste(body.resize((width,height),Image.Resampling.NEAREST),(12-round(center*scale),30-height))
 assert canvas.getchannel('A').getbbox()[3]==30
 views['female_'+name]=canvas
samples=[]
for name,im in views.items():samples.extend(p[:3]for p in sprite.grade_sprite(im,name,False).getdata()if p[3]>=160)
palette=Image.new('RGB',(len(samples),1));palette.putdata(samples)
sprite.CHARACTER_PALETTE=palette.quantize(colors=32,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
with (root/'female_sprites.hpp').open('w')as out:
 out.write('// Generated by tools/build_female.py. Original female farmer, source art/world-v2/farmer-female-v2.png.\n#pragma once\n#include "pixel_sprite.hpp"\nnamespace sprites {\n')
 for name,im in views.items():sprite.compile_sprite(out,name,im)
 out.write('}\n')
