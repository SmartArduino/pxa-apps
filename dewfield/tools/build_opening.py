#!/usr/bin/env python3
"""Encode the generated opening storyboard as bounded indexed RGB565 art."""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
palettes=[];frames=[]
for source in ('opening-boy.png','opening-girl.png'):
 im=Image.open(root/'art/reference'/source).convert('RGB')
 w,h=im.size
 boxes=[(4,4,w//3-5,h//2-6),(w//3+5,4,w*2//3-5,h//2-6),(w*2//3+5,4,w-4,h//2-6),(4,h//2+5,w//2-5,h-4),(w//2+5,h//2+5,w-4,h-4)]
 for scene,box in enumerate(boxes):
  src=im.crop(box);a,b=src.size
  # Cover a 3:2 canvas without stretching the source illustration.
  if a*160>b*240:
   ww=b*240//160;src=src.crop(((a-ww)//2,0,(a+ww)//2,b))
  else:
   hh=a*160//240;top=0 if scene==2 else (b-hh)//2;src=src.crop((0,top,a,top+hh))
  indexed=src.resize((240,160),Image.Resampling.NEAREST).quantize(colors=128,dither=Image.Dither.NONE)
  pal=indexed.getpalette();palettes.append([((pal[i]&248)<<8)|((pal[i+1]&252)<<3)|(pal[i+2]>>3) for i in range(0,384,3)])
  frames.append(list(indexed.tobytes()))
text='// Generated by tools/build_opening.py from the imagegen reference storyboard.\n#pragma once\n#include <cstdint>\nnamespace opening_art {\nconstexpr int Width=240,Height=160;\nconstexpr int index(int scene,bool female){return scene+(female?5:0); }\n'
for i,frame in enumerate(frames):
 (root/f'assets/opening-{i}.idx').write_bytes(bytes(frame))
for name,ctype,data in [('palette','uint16_t',palettes)]:
 text+=f'inline constexpr {ctype} {name}[10][{len(data[0])}]={{\n'
 for row in data:text+='{'+'\n'.join(','.join(map(str,row[i:i+40]))+',' for i in range(0,len(row),40))+'},\n'
 text+='};\n'
(root/'opening_art.hpp').write_text(text+'}\n')
