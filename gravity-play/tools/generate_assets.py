"""Generate the game's glyph textures and original vector icon. No network."""
from pathlib import Path
import json,shutil
from PIL import Image,ImageDraw,ImageFont
from fontTools.ttLib import TTFont
import cairosvg
root=Path(__file__).resolve().parents[1]
workspace=root.parents[2]
font_path=workspace/'factory/base/system/fonts/noto_sans_cjk_common.ttf'
font=ImageFont.truetype(str(font_path),16)
source=(root/'main.cpp').read_text()
chars=sorted(set(chr(i) for i in range(32,127))|{c for c in source if ord(c)>127})
cmap=TTFont(font_path).getBestCmap()
assert all(ord(char) in cmap for char in chars), 'Source font is missing a game glyph'
cols,cw,ch=14,18,24
per_page=cols*(256//ch)
entries=[]
for start in range(0,len(chars),per_page):
 page=start//per_page;items=chars[start:start+per_page]
 width=cols*cw;height=((len(items)+cols-1)//cols)*ch
 im=Image.new('L',(width,height));d=ImageDraw.Draw(im)
 for i,c in enumerate(items):d.text(((i%cols)*cw,(i//cols)*ch),c,font=font,fill=255)
 filename=f'font-{page}'
 (root/'resources'/f'{filename}.index8').write_bytes(im.tobytes())
 entries.append(dict(path=f'assets/{filename}.pxr',kind='index8',source=f'resources/{filename}.index8',width=width,height=height))
(root/'resources.json').write_text(json.dumps({'assets':entries},indent=2)+'\n')
header='// Generated by tools/generate_assets.py; glyph artwork is SIL OFL 1.1.\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace gravity {\n'
header+=f'inline constexpr unsigned font_pages={len(entries)},font_columns={cols},font_cell_w={cw},font_cell_h={ch},font_per_page={per_page};\n'
header+=f'inline constexpr std::array<uint32_t,{len(chars)}> font_codes={{'+','.join(str(ord(c)) for c in chars)+'};\n'
header+=f'inline constexpr std::array<uint8_t,{len(chars)}> font_advance={{'+','.join(str(max(4,min(cw,round(font.getlength(c))))) for c in chars)+'};\n}\n'
(root/'font.hpp').write_text(header)
for name in ['NOTICE','OFL.txt','OFL-Latin.txt']:shutil.copyfile(font_path.parent/name,root/'assets'/('FONT-'+name))
shutil.copyfile(workspace/'deps/pxa-system/LICENSE',root/'assets/PXA-SDK-LICENSE.txt')
cairosvg.svg2png(url=str(root/'assets/icon.svg'),write_to=str(root/'assets/icon.png'),output_width=96,output_height=96)
print(f'{len(chars)} glyphs, {len(entries)} textures; original SVG icon rendered')
