#!/usr/bin/env python3
"""Fetch pinned art/audio and build RGB565 sprites and 16 kHz PCM; Pillow + ffmpeg."""
from pathlib import Path
from urllib.request import urlopen
from urllib.parse import quote
import concurrent.futures, hashlib, json, subprocess
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
REV='0f2eb314a17213da0c0ce3b9d9c4693e2ed6ef96'
BASE=f'https://raw.githubusercontent.com/yairm210/Unciv/{REV}/'
terrain=['Grassland','Plains','Desert','Hill','Mountain','Forest','Coast','Ocean','City center','Mine']
units=['Settler','Warrior','Scout','Worker','Archer','Swordsman']
sounds=['click','whoosh','chimes','paper','metalhit','arrow']
items=[(n,'android/Images.Tilesets/TileSets/FantasyHex/Tiles/'+n+'.png','CC-BY-4.0','CuddlyClover and Unciv contributors') for n in terrain]
items += [(n,'android/Images.AbsoluteUnits/TileSets/AbsoluteUnits/Units/'+n+'.png','CC-BY-4.0','letstalkaboutdune') for n in units]
items += [(n,'android/assets/sounds/'+n+'.mp3','CC0-1.0',a) for n,a in zip(sounds,['EathanMarkson','dave.des','Bastianhallo','stijn','SlavicMagic','Twisted_Euphoria'])]
icon_specs=[
 ('ui_gold','android/Images.Icons/StatIcons/Gold.png','CC-BY-3.0','Eliricon'),
 ('ui_science','android/Images.Icons/StatIcons/Science.png','CC-BY-3.0','Delwar Hossain'),
 ('ui_culture','android/Images.Icons/StatIcons/Culture.png','CC-BY-3.0','Naomi Atkinson'),
 ('ui_food','android/Images.Icons/StatIcons/Food.png','CC-BY-3.0','Pedro Gonçalves'),
 ('ui_production','android/Images.Icons/StatIcons/Production.png','CC-BY-3.0','Alex Bickov'),
 ('ui_population','android/Images.Icons/StatIcons/Population.png','CC-BY-3.0 OR Public-Domain','Stéphanie Rusch'),
 ('ui_options','android/Images.Icons/OtherIcons/Options.png','CC-BY-3.0 OR Public-Domain','Thengakola'),
 ('ui_monument','android/Images.ConstructionIcons/BuildingIcons/Monument.png','CC-BY-3.0 OR Public-Domain','Eliricon'),
 ('ui_granary','android/Images.ConstructionIcons/BuildingIcons/Granary.png','CC-BY-3.0 OR Public-Domain','Pedro Santos'),
 ('ui_barracks','android/Images.ConstructionIcons/BuildingIcons/Barracks.png','CC-BY-3.0 OR Public-Domain','Creaticca Creative Agency'),
 ('ui_logo','android/assets/ExtraImages/Icons/Unciv128.png','CC-BY-4.0','yairm210 and u-ndefine; see NOTICE for included CC BY 3.0 components')]
items+=icon_specs
overlay_specs=[(n,'android/Images.Tilesets/TileSets/FantasyHex/'+p+'.png',
                'CC-BY-4.0','CuddlyClover and Unciv contributors')
               for n,p in [('map_highlight','Highlight'),('map_crosshair','Crosshair')]]
items+=overlay_specs
previous=json.loads((ROOT/'assets/sources.json').read_text()) if (ROOT/'assets/sources.json').exists() else {}
expected={item['path']:item['sha256'] for item in previous.get('assets',[])}
def fetch(item):
 n,p,lic,a=item; dest=ROOT/'source-assets/upstream'/Path(p).name.replace(' ','_')
 if not dest.exists(): dest.write_bytes(urlopen(BASE+quote(p),timeout=45).read())
 actual=hashlib.sha256(dest.read_bytes()).hexdigest()
 if p in expected and expected[p]!=actual: raise ValueError(f'Asset digest mismatch: {p}')
 return dict(file=str(dest.relative_to(ROOT)),path=p,sha256=actual,license=lic,author=a)
with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool: manifest=list(pool.map(fetch,items))
(ROOT/'assets/sources.json').write_text(json.dumps(dict(repository='https://github.com/yairm210/Unciv',revision=REV,assets=manifest,**({'music':previous['music']} if 'music' in previous else {})),indent=2)+'\n')
out=['// Generated by tools/assets.py. Art: CC BY 3.0 / 4.0; see assets/NOTICE.md.','#pragma once','#include <stdint.h>','namespace art {','struct Sprite { const uint16_t *rgb; const uint8_t *alpha; int w,h; };']
paths={n:ROOT/'source-assets/upstream'/Path(path).name.replace(' ','_') for n,path,_,_ in items}
for name in terrain+units+[i[0] for i in icon_specs+overlay_specs]:
 im=Image.open(paths[name]).convert('RGBA')
 # Feature PNGs contain trees/rocks, not an opaque ground tile. Match the
 # upstream base + feature composition, bottom-aligned at the native scale.
 if name in ['Forest','Hill','Mountain']:
  base=Image.open(paths['Grassland']).convert('RGBA')
  combined=Image.new('RGBA',(max(base.width,im.width),max(base.height,im.height)))
  combined.alpha_composite(base,((combined.width-base.width)//2,combined.height-base.height))
  combined.alpha_composite(im,((combined.width-im.width)//2,combined.height-im.height))
  im=combined
 im=im.crop(im.getbbox()) if name in units or name.startswith('ui_') else im
 im.thumbnail((64,64) if name=='ui_logo' else (40,40),Image.Resampling.LANCZOS)
 ident=name.lower().replace(' ','_'); rgb=[]; alpha=[]
 for r,g,b,a in im.getdata():rgb.append(((r&248)<<8)|((g&252)<<3)|(b>>3));alpha.append(a)
 out += [f'inline constexpr uint16_t {ident}_rgb[]={{'+','.join(map(str,rgb))+'};',f'inline constexpr uint8_t {ident}_alpha[]={{'+','.join(map(str,alpha))+'};',f'inline constexpr Sprite {ident}={{{ident}_rgb,{ident}_alpha,{im.width},{im.height}}};']
out+=['}'];(ROOT/'art.hpp').write_text('\n'.join(out)+'\n')
# Short effects are prepared once by Assets 1.3. The Host owns their clock,
# so rendering and AI never have to pump 20 ms PCM blocks.
audio_dir=ROOT/'assets/audio';audio_dir.mkdir(exist_ok=True)
for name in sounds:
 raw=subprocess.check_output(['ffmpeg','-v','error','-i',str(ROOT/'source-assets/upstream'/f'{name}.mp3'),'-t','1.2','-f','s16le','-ar','16000','-ac','1','-'])
 import struct
 pcm=list(struct.unpack('<'+'h'*(len(raw)//2),raw))
 peak=max(1,max(map(abs,pcm)))
 # Remove encoder silence, retain a short lead-in and fit the 1 second Host
 # sound bound. Fade truncated tails to avoid a discontinuity.
 first=next((i for i,v in enumerate(pcm) if abs(v)>peak/100),0)
 pcm=pcm[max(0,first-80):][:16000]
 for i in range(min(80,len(pcm))):
  pcm[-1-i]=int(pcm[-1-i]*i/80)
 (audio_dir/f'{name}.pcm').write_bytes(bytes(max(0,min(255,128+round(v*9000/peak/256))) for v in pcm))
# The unmodified upstream application icon, with its complete attribution.
(ROOT/'assets/icon.png').write_bytes((ROOT/'assets/upstream/Unciv128.png').read_bytes())
print('Generated',len(items),'pinned assets')

# The upstream default download offer, with independently pinned source and
# output digests. Keep the original MP3 out of the small device package.
music=previous.get('music')
if music:
 dest=ROOT/music['file']
 if not dest.exists():
  raw=urlopen(music['source'],timeout=45).read()
  if hashlib.sha256(raw).hexdigest()!=music['source_sha256']:
   raise ValueError('Music source digest mismatch')
  encoded=subprocess.check_output(['ffmpeg','-v','error','-i','pipe:0','-map_metadata','-1',
    '-fflags','+bitexact','-flags:a','+bitexact','-ac','1','-ar','16000','-c:a','libvorbis',
    '-b:a','24000','-metadata','title=Thatched Villagers','-metadata','artist=Kevin MacLeod',
    '-metadata','copyright=CC BY 4.0 https://creativecommons.org/licenses/by/4.0/',
    '-f','ogg','pipe:1'],input=raw)
  dest.write_bytes(encoded)
 if hashlib.sha256(dest.read_bytes()).hexdigest()!=music['sha256']:
  raise ValueError('Music output digest mismatch; use the pinned ffmpeg conversion')
