#!/usr/bin/env bash
set -euo pipefail
app_dir="$(cd "$(dirname "$0")/.." && pwd)"
artifacts_dir="${1:-$app_dir/../../artifacts/unciv/$(date +%Y%m%d-%H%M%S)}"
mkdir -p "$artifacts_dir"
compiler="${CXX:-g++}"
flags=(-std=c++20 -O1 -g -Wall -Wextra -Wpedantic -Werror -fsanitize=address,undefined -fno-omit-frame-pointer)
"$compiler" "${flags[@]}" "$app_dir/tests/tactics_test.cpp" "$app_dir/core.cpp" -o "$artifacts_dir/tactics-test"
"$artifacts_dir/tactics-test" "$app_dir/tests/legacy-v6-large.bin" > "$artifacts_dir/tactics-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/ai_test.cpp" "$app_dir/core.cpp" -o "$artifacts_dir/ai-test"
"$artifacts_dir/ai-test" > "$artifacts_dir/ai-test.log"
"$compiler" "${flags[@]}" -Wno-attributes -I"$app_dir/../../../deps/pxa-system/sdk/guest-c/include" "$app_dir/tests/audio_test.cpp" "$app_dir/audio.cpp" -o "$artifacts_dir/audio-test"
"$artifacts_dir/audio-test" > "$artifacts_dir/audio-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/core_test.cpp" "$app_dir/core.cpp" -o "$artifacts_dir/core-test"
"$artifacts_dir/core-test" "$app_dir/tests/legacy-save.bin" > "$artifacts_dir/core-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/strategy_test.cpp" "$app_dir/core.cpp" -o "$artifacts_dir/strategy-test"
"$artifacts_dir/strategy-test" "$app_dir/tests/legacy-v2-large.bin" "$app_dir/tests/legacy-v3-large.bin" > "$artifacts_dir/strategy-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/progression_test.cpp" "$app_dir/core.cpp" -o "$artifacts_dir/progression-test"
"$artifacts_dir/progression-test" "$app_dir/tests/legacy-v4-large.bin" > "$artifacts_dir/progression-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/production_test.cpp" "$app_dir/core.cpp" -o "$artifacts_dir/production-test"
"$artifacts_dir/production-test" "$app_dir/tests/legacy-v5-large.bin" > "$artifacts_dir/production-test.log"
"$compiler" "${flags[@]}" -DPXA_POCKET_STUDIO=1 -DPXA_POCKET_FILL=1 "$app_dir/tests/ui_test.cpp" "$app_dir/main.cpp" "$app_dir/core.cpp" -o "$artifacts_dir/ui-test"
"$artifacts_dir/ui-test" > "$artifacts_dir/ui-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/save_store_test.cpp" "$app_dir/save_store.cpp" -o "$artifacts_dir/save-store-test"
"$artifacts_dir/save-store-test" > "$artifacts_dir/save-store-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/overlay_raster_test.cpp" -o "$artifacts_dir/overlay-raster-test"
"$artifacts_dir/overlay-raster-test" > "$artifacts_dir/overlay-raster-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/scanline_cache_test.cpp" -o "$artifacts_dir/scanline-cache-test"
"$artifacts_dir/scanline-cache-test" > "$artifacts_dir/scanline-cache-test.log"
"$compiler" "${flags[@]}" "$app_dir/tests/pinch_tracker_test.cpp" -o "$artifacts_dir/pinch-tracker-test"
"$artifacts_dir/pinch-tracker-test" > "$artifacts_dir/pinch-tracker-test.log"
cat "$artifacts_dir/tactics-test.log" "$artifacts_dir/ai-test.log" "$artifacts_dir/audio-test.log" "$artifacts_dir/production-test.log" "$artifacts_dir/progression-test.log" "$artifacts_dir/strategy-test.log" "$artifacts_dir/save-store-test.log" "$artifacts_dir/core-test.log" "$artifacts_dir/ui-test.log" "$artifacts_dir/overlay-raster-test.log" "$artifacts_dir/scanline-cache-test.log" "$artifacts_dir/pinch-tracker-test.log"
