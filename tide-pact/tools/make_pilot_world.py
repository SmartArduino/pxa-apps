"""Pack Natural Earth land masks into overlapping windows for world pilotage."""
import argparse
import io
import json
import math
import struct
import zipfile

from PIL import Image, ImageDraw
import shapefile

from make_chart import ROOT, W, H, WEST, NORTH, SX, SY

SCALE = 8
TILE_WIDTH, TILE_HEIGHT = 256, 128
STEP_X, STEP_Y = TILE_WIDTH - 2 * SCALE, TILE_HEIGHT - 2 * SCALE
COLUMNS = math.ceil(W * SCALE / STEP_X)
ROWS = math.ceil(H * SCALE / STEP_Y)


def land_mask(archive_path):
    mask = Image.new("1", (W * SCALE, H * SCALE))
    draw = ImageDraw.Draw(mask)
    with zipfile.ZipFile(archive_path) as archive:
        shape = next(name for name in archive.namelist() if name.endswith(".shp"))
        reader = shapefile.Reader(shp=io.BytesIO(archive.read(shape)))
        for feature in reader.iterShapes():
            lo, bot, hi, top = feature.bbox
            if hi < WEST or lo > WEST + W / SX or bot > NORTH or top < NORTH - H / SY:
                continue
            starts = [*feature.parts, len(feature.points)]
            for first, last in zip(starts, starts[1:]):
                points = feature.points[first:last]
                clockwise = sum(x * v - y * u for (x, y), (u, v) in zip(points, points[1:])) < 0
                draw.polygon([((lon - WEST) * SX * SCALE - .5, (NORTH - lat) * SY * SCALE - .5)
                              for lon, lat in points], fill=255 if clockwise else 0)
    return mask


def pack_tile(raw):
    """Encode runs as length byte and value byte. Keep dense tiles verbatim."""
    if raw == raw[:1] * len(raw):
        return raw[:1]
    packed = bytearray()
    start = 0
    while start < len(raw):
        end = start + 1
        while end < min(start + 255, len(raw)) and raw[end] == raw[start]:
            end += 1
        packed.extend((end - start, raw[start]))
        start = end
    return packed if len(packed) < len(raw) else raw


def write_tiles(mask):
    # A one-world-cell collar lets ships reach the next window before switching.
    atlas = Image.new("1", ((COLUMNS - 1) * STEP_X + TILE_WIDTH,
                            (ROWS - 1) * STEP_Y + TILE_HEIGHT), 255)
    atlas.paste(mask, (SCALE, SCALE))
    tiles = []
    for row in range(ROWS):
        for column in range(COLUMNS):
            x, y = column * STEP_X, row * STEP_Y
            tile = atlas.crop((x, y, x + TILE_WIDTH, y + TILE_HEIGHT))
            tiles.append(pack_tile(tile.tobytes()))
    index = bytearray()
    offset = 4 * (len(tiles) + 1)
    for tile in tiles:
        index.extend(struct.pack("<I", offset))
        offset += len(tile)
    index.extend(struct.pack("<I", offset))
    (ROOT / "assets/sea/pilot-world.bin").write_bytes(index + b"".join(tiles))
    print(f"{len(tiles)} charts, {offset:,} bytes")


def write_berths(mask):
    data = json.loads((ROOT / "world.json").read_text())
    lines = []
    for entry in data["ports"] + data["sites"]:
        port = len(entry) == 10
        lon, lat = entry[5:7] if port else entry[4:6]
        x, y = round((lon - WEST) * SX * SCALE), round((NORTH - lat) * SY * SCALE)
        wet = ((u, v) for v in range(max(0, y - 40), min(mask.height, y + 41))
               for u in range(max(0, x - 40), min(mask.width, x + 41)) if not mask.getpixel((u, v)))
        u, v = min(wet, key=lambda point: (point[0] - x)**2 + (point[1] - y)**2)
        lines.append(f"    {{{u * 2 + 1},{v * 2 + 1}}}, // {entry[0]}")
    (ROOT / "pilot_world_data.hpp").write_text(
        "// Generated by tools/make_pilot_world.py from world.json and Natural Earth land.\n"
        "inline constexpr Point PilotWorldBerths[]{\n" + "\n".join(lines) + "\n};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("natural_earth_land_zip")
    mask = land_mask(parser.parse_args().natural_earth_land_zip)
    write_berths(mask)
    write_tiles(mask)


if __name__ == "__main__":
    main()
