"""Pack Natural Earth land masks into overlapping windows for world pilotage."""
import argparse
import io
import json
import math
import struct
import zipfile

from PIL import Image, ImageDraw
import shapefile

from make_chart import ROOT, W, H, NORTH, SX, SY, draw_land, east_of_seam, ordered_places, port_names
from pilot_berths import edge_water, settlement_mark, shoreline_berth

SCALE = 8
TILE_WIDTH, TILE_HEIGHT = 256, 128
STEP_X, STEP_Y = TILE_WIDTH - 2 * SCALE, TILE_HEIGHT - 2 * SCALE
COLUMNS = math.ceil(W * SCALE / STEP_X)
ROWS = math.ceil(H * SCALE / STEP_Y)


def land_mask(archive_path):
    mask = Image.new("1", (W * SCALE, H * SCALE))
    draw = ImageDraw.Draw(mask)
    with zipfile.ZipFile(archive_path) as archive:
        shape = next(name for name in archive.namelist() if name.endswith(".shp"))
        reader = shapefile.Reader(shp=io.BytesIO(archive.read(shape)))
        draw_land(draw, reader, SCALE, -.5)
    return mask


def pack_tile(raw):
    """Encode runs as length byte and value byte. Keep dense tiles verbatim."""
    if raw == raw[:1] * len(raw):
        return raw[:1]
    packed = bytearray()
    start = 0
    while start < len(raw):
        end = start + 1
        while end < min(start + 255, len(raw)) and raw[end] == raw[start]:
            end += 1
        packed.extend((end - start, raw[start]))
        start = end
    return packed if len(packed) < len(raw) else raw


def write_tiles(mask):
    # A one-world-cell collar lets ships reach the next window before switching.
    atlas = Image.new("1", ((COLUMNS - 1) * STEP_X + TILE_WIDTH,
                            (ROWS - 1) * STEP_Y + TILE_HEIGHT), 255)
    atlas.paste(mask, (SCALE, SCALE))
    tiles = []
    for row in range(ROWS):
        for column in range(COLUMNS):
            x, y = column * STEP_X, row * STEP_Y
            tile = atlas.crop((x, y, x + TILE_WIDTH, y + TILE_HEIGHT))
            tiles.append(pack_tile(tile.tobytes()))
    index = bytearray()
    offset = 4 * (len(tiles) + 1)
    for tile in tiles:
        index.extend(struct.pack("<I", offset))
        offset += len(tile)
    index.extend(struct.pack("<I", offset))
    (ROOT / "assets/sea/pilot-world.bin").write_bytes(index + b"".join(tiles))
    print(f"{len(tiles)} charts, {offset:,} bytes")


def write_berths(mask):
    data = json.loads((ROOT / "world.json").read_text())
    marks, lines = {}, []
    wet = lambda u, v: not mask.getpixel((u, v))

    def mark(lon, lat, settlement):
        x, y = east_of_seam(lon) * SX * SCALE, (NORTH - lat) * SY * SCALE
        if settlement:
            x, y = settlement_mark(x, y, mask.size, wet, SY / SX * math.cos(math.radians(lat)))
        return round(x * 16), round(y * 16)

    def waypoint(lon, lat, reach):
        x, y = round(east_of_seam(lon) * SX * SCALE), round((NORTH - lat) * SY * SCALE)
        wet = ((u, v) for v in range(max(0, y - reach), min(mask.height, y + reach + 1))
               for u in range(max(0, x - reach), min(mask.width, x + reach + 1)) if not mask.getpixel((u, v)))
        u, v = min(wet, key=lambda point: (point[0] - x)**2 + (point[1] - y)**2)
        return u * 2 + 1, v * 2 + 1

    def berth(lon, lat, reach):
        x, y = east_of_seam(lon) * SX * SCALE, (NORTH - lat) * SY * SCALE
        bound = reach + 12
        bounds = (max(0, int(x) - bound), max(0, int(y) - bound),
                  min(mask.width, int(x) + bound + 1), min(mask.height, int(y) + bound + 1))
        u, v = shoreline_berth(x, y, reach, mask.size, wet, edge_water(bounds, wet),
                               SY / SX * math.cos(math.radians(lat)), wet)
        return u * 2 + 1, v * 2 + 1

    transfers = data.get("pilot_transfers", {})
    villages = {entry[0] for entry in data["villages"]}
    for entry in ordered_places(data):
        name = entry[0]
        if len(entry) == 10 or name in villages:
            mark_x, mark_y = mark(*entry[3:5], True)
            if len(entry) == 10:
                marks[name] = f"    {{{mark_x},{mark_y}}}, // {name}"
            x, y = berth(*transfers.get(name, entry[3:5]), 14)
        else:
            x, y = waypoint(*entry[4:6], 40)
        lines.append(f"    {{{x},{y}}}, // {name}")
    places = []
    for name, lon, lat, kind, note, *options in json.loads((ROOT / "pilot_world_places.json").read_text()):
        x, y = mark(lon, lat, kind != "point")
        bx, by = map(lambda value: value * 8, berth(*options[0], 12)) if options else (-1, -1)
        transfer = ", true" if len(options) > 1 and options[1] else ""
        n, copy = (json.dumps(value, ensure_ascii=False) for value in (name, note))
        places.append(f"    {{{n}, {copy}, {{{x},{y}}}, {{{bx},{by}}}, Pilot{kind.title()}{transfer}}},")
    (ROOT / "pilot_world_data.hpp").write_text(
        "// Generated by tools/make_pilot_world.py from the world and coastal place data.\n"
        "inline constexpr int PilotTransferPorts[]{" + ", ".join(transfers) + "};\n"
        "inline constexpr Point PilotWorldPortMarks[]{\n" + "\n".join(marks[name] for name in port_names(data)) + "\n};\n"
        "inline constexpr Point PilotWorldBerths[]{\n" + "\n".join(lines) + "\n};\n"
        "inline constexpr PilotSite PilotCoastalSites[]{\n" + "\n".join(places) + "\n};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("natural_earth_land_zip")
    mask = land_mask(parser.parse_args().natural_earth_land_zip)
    write_berths(mask)
    write_tiles(mask)


if __name__ == "__main__":
    main()
