#!/usr/bin/env python3
"""Generate one compact, relocation-free T9 table from the licensed snapshot."""
import argparse
import bisect
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    rows = [tuple(line.split('\t')) for line in (root / 'data/t9.tsv').read_text().splitlines()
            if line and not line.startswith('#')]
    if not rows or rows != sorted(rows) or len(set(rows)) != len(rows):
        raise SystemExit('T9 rows must be unique and sorted by digits, then spelling')
    keys = dict(zip('abcdefghijklmnopqrstuvwxyz', '22233344455566677778889999'))
    for digits, spelling in rows:
        if not spelling or any(c not in keys for c in spelling) or ''.join(keys[c] for c in spelling) != digits:
            raise SystemExit(f'Invalid T9 row: {digits} {spelling}')
    maximum = max(len(spelling) for _, spelling in rows)
    if maximum > 6 or len(rows) > 65535:
        raise SystemExit('T9 rows exceed the spelling/range representation')
    header = f'''/* SPDX-FileCopyrightText: 2026 lvgl_pinyin_ime contributors
 * SPDX-License-Identifier: Apache-2.0
 * Generated by tools/generate_t9_table.py; do not edit. */
#pragma once
#include <stdint.h>
#define IME_T9_SYLLABLE_COUNT {len(rows)}
#define IME_T9_SYLLABLE_MAX_DIGITS {maximum}
typedef struct {{
    char syllable[IME_T9_SYLLABLE_MAX_DIGITS + 1];
    uint8_t length;
}} ime_t9_syllable_t;
typedef struct {{ uint16_t begin, end; }} ime_t9_range_t;
#ifdef __cplusplus
extern "C" {{
#endif
extern const ime_t9_syllable_t ime_t9_syllables[IME_T9_SYLLABLE_COUNT];
/* First 64 entries: two digits (22..99); last eight: one digit (2..9). */
extern const ime_t9_range_t ime_t9_prefixes[72];
extern const char ime_t9_letter_digits[27];
#ifdef __cplusplus
}}
#endif
'''
    def entry(digits, spelling):
        return f'    {{"{spelling}", {len(spelling)}}},\n'
    digits = [d for d, _ in rows]
    prefixes = [a + b for a in '23456789' for b in '23456789'] + list('23456789')
    ranges = ''.join(f'    {{{bisect.bisect_left(digits, p)}, {bisect.bisect_left(digits, p + ":")}}}, /* {p} */\n'
                     for p in prefixes)
    source = ('/* SPDX-FileCopyrightText: 2026 lvgl_pinyin_ime contributors\n'
              ' * SPDX-License-Identifier: Apache-2.0\n'
              ' * Generated by tools/generate_t9_table.py; do not edit. */\n'
              '#include "ime_t9_syllables.h"\n'
              'const ime_t9_syllable_t ime_t9_syllables[IME_T9_SYLLABLE_COUNT] = {\n' +
              ''.join(entry(d, s) for d, s in rows) + '};\n' +
              'const ime_t9_range_t ime_t9_prefixes[72] = {\n' + ranges + '};\n' +
              'const char ime_t9_letter_digits[27] = "22233344455566677778889999";\n')
    for name, text in [('ime_t9_syllables.h', header), ('ime_t9_syllables.c', source)]:
        path = root / 'generated' / name
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f'Stale generated table: {path}')
        else:
            path.write_text(text)
    print(f'T9: {len(rows)} rows, {len(rows)*(maximum+2)+72*4+27} immutable bytes, one definition')


if __name__ == '__main__':
    main()
