#!/usr/bin/env python3
"""Generate a compact immutable table, or refresh its licensed source snapshot."""
import argparse
from collections import defaultdict
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
REVISION = '037169998150a768ff43863fc44d563222d4b801'


def extract(reference):
    revision = subprocess.check_output(['git', '-C', str(reference), 'rev-parse', 'HEAD'], text=True).strip()
    if revision != REVISION:
        raise SystemExit(f'Reference must be at {REVISION}')
    source = reference / 'data/dict/rawdict_utf16_65105_freq.txt'
    rows = defaultdict(dict)
    for line in source.read_text(encoding='utf-16').splitlines():
        fields = line.split()
        if len(fields) != 4 or len(fields[0]) != 1 or not 0x4e00 <= ord(fields[0]) <= 0x9fff:
            continue
        try:
            fields[0].encode('gb2312')
        except UnicodeEncodeError:
            continue
        character, frequency, _, spelling = fields
        spelling = {'lve': 'lue', 'nve': 'nue'}.get(spelling, spelling)
        rows[spelling][character] = max(float(frequency), rows[spelling].get(character, 0))
    header = (f'# SPDX-License-Identifier: Apache-2.0\n'
              f'# Derived from lvgl_pinyin_ime {REVISION}\n'
              f'# rawdict SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
              '# GB2312 Han characters, descending source frequency; no words or sentence model.\n')
    return header + ''.join(f'{spelling}\t' + ''.join(sorted(characters, key=lambda c: (-characters[c], ord(c)))) + '\n'
                            for spelling, characters in sorted(rows.items()))


def generate(text):
    rows = []
    characters = []
    previous = ''
    for line in text.splitlines():
        if not line or line.startswith('#'):
            continue
        spelling, values = line.split('\t')
        if spelling <= previous or not spelling.isascii() or not spelling.isalpha() or len(spelling) > 6:
            raise SystemExit(f'Invalid spelling: {spelling}')
        if not values or len(set(values)) != len(values):
            raise SystemExit(f'Empty or duplicate candidates: {spelling}')
        if any(not 0x4e00 <= ord(c) <= 0x9fff for c in values):
            raise SystemExit('Only BMP Han characters are supported')
        rows.append((spelling, len(characters), len(values)))
        characters.extend(ord(c) for c in values)
        previous = spelling
    if len(characters) > 65535:
        raise SystemExit('Character offsets exceed uint16_t')
    output = ['// SPDX-License-Identifier: Apache-2.0', '// Generated by tools/generate_table.py; do not edit.',
              '#pragma once', '#include <cstdint>', 'namespace pinyin_lite::table {',
              'struct Syllable { char spelling[7]; std::uint16_t offset, count; };',
              'inline constexpr Syllable syllables[] = {']
    output.extend(f'    {{"{s}", {o}, {n}}},' for s, o, n in rows)
    output.append('};\ninline constexpr std::uint16_t characters[] = {')
    output.extend('    ' + ', '.join(f'0x{v:04x}' for v in characters[i:i+12]) + ','
                  for i in range(0, len(characters), 12))
    output.append('};\n}\n')
    print(f'syllables={len(rows)} readings={len(characters)} unique_characters={len(set(characters))} '
          f'table_bytes={len(rows)*12+len(characters)*2}')
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, help='Pinned upstream checkout to refresh data/pinyin.tsv')
    parser.add_argument('--check', action='store_true', help='Verify without modifying files')
    args = parser.parse_args()
    snapshot = ROOT / 'data/pinyin.tsv'
    text = extract(args.reference) if args.reference else snapshot.read_text()
    header = generate(text)
    target = ROOT / 'generated/characters.hpp'
    if args.check:
        if snapshot.read_text() != text or target.read_text() != header:
            raise SystemExit('Generated table is stale')
    else:
        snapshot.write_text(text)
        target.write_text(header)


if __name__ == '__main__':
    main()
