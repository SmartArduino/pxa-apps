#!/usr/bin/env python3
"""Import the original Milky Frog art/audio; convert offline for PXA.

Requires Pillow and ffmpeg. Downloaded originals stay in each app's art/;
SOURCES.json records URLs, hashes and transformations. No runtime network.
"""
import concurrent.futures
import hashlib
import json
import math
from pathlib import Path
import subprocess
import urllib.request
from PIL import Image

APPS = Path(__file__).resolve().parents[2]


def download(task):
    path, url = task
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"}), timeout=40) as response:
            data = response.read(32 * 1024 * 1024)
        path.write_bytes(data)
    return {"path": str(path.relative_to(APPS)), "url": url,
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}


def audio(source, output, rate=1, preserve=False):
    output.parent.mkdir(parents=True, exist_ok=True)
    args = ["ffmpeg", "-v", "error", "-y", "-i", str(source), "-vn", "-ac", "1"]
    # The miner changes pitch without changing duration. Render that offline.
    if rate != 1:
        filters = f"asetrate=44100*{rate},aresample=16000"
        if preserve:
            filters += f",atempo={1/rate}"
        args += ["-af", filters]
    args += ["-ar", "16000", "-f", "s16le", str(output)]
    subprocess.run(args, check=True)


def sprite(image, box):
    image = image.convert("RGBA")
    bounds = image.getbbox()
    if bounds:
        image = image.crop(bounds)
    image.thumbnail(box, Image.Resampling.LANCZOS)
    return image


def export_icon(app, source):
    """Fit source art inside the square launcher slot without distorting it."""
    image=Image.open(source).convert('RGBA')
    image.thumbnail((96,96),Image.Resampling.LANCZOS)
    icon=Image.new('RGBA',(96,96))
    icon.alpha_composite(image,((96-image.width)//2,(96-image.height)//2))
    icon.save(app/'assets'/'icon.png',optimize=True)


def refresh_generated_sources(app):
    data=json.loads((app/'SOURCES.json').read_text())
    data['generated']=[{'path':str(f.relative_to(app)),'sha256':hashlib.sha256(f.read_bytes()).hexdigest()}
        for f in [*sorted(app.glob('*es.hpp')),*sorted((app/'assets').glob('*.s16')),*sorted((app/'assets').glob('*.ogg')),*sorted((app/'assets'/'images').glob('*.png')),app/'assets'/'icon.png']]
    provenance=app/'art'/'icon-rain-square.json'
    if provenance.exists():data['icon_artwork']=json.loads(provenance.read_text())
    data['icon_export']='Fit artwork proportionally inside a 96x96 RGBA square using Lanczos; center with padding; never stretch to a different aspect ratio.'
    (app/'SOURCES.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    (app/'assets'/'SOURCES.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')


def emit_sprites(app, images, output='sprites.hpp'):
    native = app/'assets'/'images'
    native.mkdir(parents=True, exist_ok=True)
    animations = [(n,im) for n,im in images if n.startswith('laugh_')]
    regions = {}
    rare_regions = {}
    rares=[(n,im) for n,im in images if n.startswith('rare_')]
    for side,count in [(64,4),(32,8)]:
        for start in range(0,len(rares),count):
            atlas=Image.new('RGBA',(side*count,side));path=f'assets/images/rare-{side}-{start//count}.png'
            for slot,(name,im) in enumerate(rares[start:start+count]):
                frame=sprite(im,(side,side));x=slot*side+(side-frame.width)//2;y=(side-frame.height)//2
                atlas.paste(frame,(x,y));rare_regions[name,side]=(path,atlas.width,atlas.height,x,y,frame.width,frame.height)
            atlas.save(app/path,optimize=True)
    # Four original animation frames share one bounded, prepared image.
    # This avoids decoding/loading on every animation tick.
    for start in range(0,len(animations),4):
        atlas = Image.new('RGBA',(320,104))
        path = f'assets/images/laugh-atlas-{start//4}.png'
        for slot,(name,im) in enumerate(animations[start:start+4]):
            frame=sprite(im,(80,104));x=slot*80+(80-frame.width)//2;y=(104-frame.height)//2
            atlas.paste(frame,(x,y))
            regions[name]=(path,320,104,x,y,frame.width,frame.height)
        atlas.save(app/path,optimize=True)
    lines = ['// Generated by common/milky-frog/prepare_assets.py; see SOURCES.json.',
             '#pragma once', '#include "../common/milky-frog/media.hpp"', 'namespace art {']
    for name, original in images:
        image=sprite(original,(38,32) if app.name=='milkyfrog-2048' else (40,70))
        if name in regions:
            large=small=medium=tiny=regions[name]
        else:
            sizes=[]
            for side in ([128] if name.startswith('rare_') else [512,128,64,32]):
                full=sprite(original,(side,side))
                if full.width*full.height>56000:
                    ratio=math.sqrt(56000/(full.width*full.height));full=full.resize((int(full.width*ratio),int(full.height*ratio)),Image.Resampling.LANCZOS)
                path=f'assets/images/{name}-{side}.png'
                full.save(app/path,optimize=True)
                sizes.append((path,full.width,full.height,0,0,full.width,full.height))
            if name.startswith('rare_'):large=small=sizes[0];medium=rare_regions[name,64];tiny=rare_regions[name,32]
            else:large,small,medium,tiny=sizes
        def region(r):return '{"'+r[0]+'",'+','.join(map(str,r[1:]))+'}'
        pixels = []
        for r, g, b, a in image.getdata():
            color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            # RGB565 + 4-bit straight coverage in one word.
            pixels.append(color | ((a * 15 // 255) << 16))
        lines.append(f'inline constexpr uint32_t {name}_pixels[] = {{')
        lines += [','.join(hex(p) for p in pixels[i:i+24])+',' for i in range(0, len(pixels), 24)]
        lines += ['};', f'inline constexpr milky::Sprite {name}{{{image.width},{image.height},{name}_pixels,{region(large)},{region(small)},{region(medium)},{region(tiny)}}};']
    lines += ['}', '']
    (app / output).write_text('\n'.join(lines))


def main():
    plans = {}
    base = 'https://game.0z.hk/game/2048/'
    plans['milkyfrog-2048'] = [(f'tile-{2**i}.webp', base+f'assets/tiles/tile-{2**i}.webp') for i in range(1,13)]
    sounds = [f'laugh-{i}.mp3' for i in range(1,5)] + [f'ice-{i}.mp3' for i in range(1,4)] + ['andy-1.mp3', 'bgm.mp3']
    plans['milkyfrog-2048'] += [(s, base+'assets/'+s) for s in sounds]
    base = 'https://naiwa-milk-rain.pages.dev/assets/'
    plans['milkyfrog-rain'] = [(n+'.png', base+n+'.png') for n in ['frog','angry','heart','face','coin','wing','laugh']]
    plans['milkyfrog-rain'] += [(s,base+s) for s in ['laugh.mp3','ding.mp3','stage1.mp3','andy.mp3']]
    base = 'https://66970010-boop.github.io/frog-miner/assets/'
    plans['milkyfrog-miner'] = [(s, base+s) for s in ['frog-small.webp','frog-big.webp','diamond-small.webp','ice-1.webp','ice-2.webp','ice-3.webp','dandan-head.webp','od-boss.webp','od-angry.webp','laugh-sheet2.webp']]
    plans['milkyfrog-miner'] += [(f'frog-rare-{i}.webp',base+f'frog-rare-{i}.webp') for i in range(1,48)]
    plans['milkyfrog-miner'] += [(s,base+s) for s in sounds if s!='andy-1.mp3'] + [('andy-1.mp3',base+'special/andy-1.mp3'),('laugh-audio.mp3',base+'laugh-audio.mp3')]
    tasks = [(APPS/app/'art'/name,url) for app, files in plans.items() for name,url in files]
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
        records = list(executor.map(download, tasks))
    for name in plans:
        app = APPS/name
        (app/'assets').mkdir(exist_ok=True)
        for generated in (app/'assets'/'images').glob('*.png'):generated.unlink()
        metadata = {'sources':[{**r,'path':str(Path(r['path']).relative_to(name))} for r in records if f'/{name}/' in '/'+r['path']],
            'transformations':['Images: crop transparent padding, Lanczos resize, RGB565 + 4-bit alpha.',
                               'Audio: original recordings downmixed to signed 16-bit 16 kHz mono.',
                               'Pitch variants rendered offline; miner compensates tempo to retain duration.'],
            'rights':'Third-party images/recordings retain their original rights; meme status is not a license. See THIRD-PARTY.txt.'}
        (app/'SOURCES.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2)+'\n')
    app=APPS/'milkyfrog-2048'
    images=[(f'tile_{i}',Image.open(app/'art'/f'tile-{2**i}.webp')) for i in range(1,13)]
    emit_sprites(app,images)
    for n,rate in [(1,1.75),(2,1.35),(3,1),(4,.85)]:
        audio(app/'art'/f'laugh-{n}.mp3',app/'assets'/f'laugh-{n}.s16',rate)
    for i in range(1,4): audio(app/'art'/f'ice-{i}.mp3',app/'assets'/f'ice-{i}.s16')
    audio(app/'art'/'andy-1.mp3',app/'assets'/'andy.s16')
    audio(app/'art'/'laugh-4.mp3',app/'assets'/'lose.s16',.45)
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(app/'art'/'bgm.mp3'),'-ac','1','-ar','16000','-c:a','libvorbis','-q:a','2',str(app/'assets'/'bgm.ogg')],check=True)
    export_icon(app,app/'art'/'tile-2048.webp')
    app=APPS/'milkyfrog-rain'
    images=[(n,Image.open(app/'art'/(n+'.png'))) for n in ['frog','angry','heart','face','coin','wing']]
    sheet=Image.open(app/'art'/'laugh.png').convert('RGBA')
    for k in range(0,79,4):
        frame=sheet.crop(((k%10)*151+1,(k//10)*199+1,(k%10)*151+146,(k//10)*199+194))
        clean=[]
        for r,g,b,a in frame.getdata():
            excess=g-max(r,b)
            if g>100 and excess>35 and g>r*1.28 and g>b*1.3:
                a=round(a*(1-min(1,max(0,(excess-35)/70))));g=min(g,max(r,b)+18)
            clean.append((r,g,b,a))
        frame.putdata(clean);images.append((f'laugh_{k//4}',frame))
    emit_sprites(app,images)
    for n in ['laugh','ding','andy']:audio(app/'art'/(n+'.mp3'),app/'assets'/(n+'.s16'))
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(app/'art'/'stage1.mp3'),'-ac','1','-ar','16000','-c:a','libvorbis','-q:a','2',str(app/'assets'/'bgm.ogg')],check=True)
    icon_art=app/'art'/'icon-rain-square.png'
    export_icon(app,icon_art if icon_art.exists() else app/'art'/'frog.png')
    app=APPS/'milkyfrog-miner'
    names=['frog-small','frog-big','diamond-small','ice-1','ice-2','ice-3','dandan-head','od-boss','od-angry']
    images=[(n.replace('-','_'),Image.open(app/'art'/(n+'.webp'))) for n in names]
    images += [(f'rare_{i}',Image.open(app/'art'/f'frog-rare-{i}.webp')) for i in range(1,48)]
    sheet=Image.open(app/'art'/'laugh-sheet2.webp').convert('RGBA')
    for i in range(20):
        cols=sheet.width//144
        frame=sheet.crop(((i%cols)*144,(i//cols)*192,(i%cols+1)*144,(i//cols+1)*192))
        images.append((f'laugh_{i}',frame))
    emit_sprites(app,images)
    for i in range(1,5):
        for tag,rate in [('low',.8),('normal',1.35),('high',2)]:
            audio(app/'art'/f'laugh-{i}.mp3',app/'assets'/f'laugh-{i}-{tag}.s16',rate,True)
    for i in range(1,4):audio(app/'art'/f'ice-{i}.mp3',app/'assets'/f'ice-{i}.s16')
    audio(app/'art'/'andy-1.mp3',app/'assets'/'andy.s16')
    audio(app/'art'/'laugh-audio.mp3',app/'assets'/'lose.s16')
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(app/'art'/'bgm.mp3'),'-ac','1','-ar','16000','-c:a','libvorbis','-q:a','2',str(app/'assets'/'bgm.ogg')],check=True)
    export_icon(app,app/'art'/'frog-big.webp')
    for name,files in [('milkyfrog-rain',[('hero_frog','frog.png'),('hero_heart','heart.png')]),('milkyfrog-miner',[('hero_frog','frog-big.webp'),('hero_angry','od-angry.webp')])]:
        app=APPS/name;emit_sprites(app,[(n,Image.open(app/'art'/path)) for n,path in files],'heroes.hpp')
    for name in plans:
        app=APPS/name
        data=json.loads((app/'SOURCES.json').read_text())
        data['transformations'][0]='Images: crop transparent padding; Lanczos 32/64/128 px and up to 56,000 pixel RGBA variants; original animation frames packed into bounded 320x104 atlases; small RGB565 fallbacks.'
        (app/'SOURCES.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
        refresh_generated_sources(app)
    print('Imported original art and audio for all three games.')


if __name__=='__main__':main()
