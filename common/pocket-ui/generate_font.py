"""Regenerate Pocket CJK Bitmap 10 from Noto Sans CJK SC (OFL-1.1).

Requires Pillow. Only non-ASCII characters in C/C++ string literals in the
selected games/shared UI are included; comments and unrelated applications
cannot inflate the subset. The source font is not redistributed.
"""
import argparse
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
APPS = HERE.parent.parent
GAMES = ('game-2048', 'pocket-chess', 'pocket-sokoban', 'crisp-arcade',
         'pet-garden', 'marble-islands', 'lantern-grove', 'harbor-cafe',
         'tiny-elements', 'anarch')
TOKEN = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"', re.S)


def collect():
    files = [APPS / name / 'main.cpp' for name in GAMES]
    files += [APPS / 'anarch/view.hpp', APPS / 'anarch/main.c']
    for name in GAMES:
        # Anarch has a C front end and translations may live in a header.
        root = APPS / name / 'src'
        if root.exists():
            files += [p for p in root.rglob('*') if p.suffix in ('.c', '.cpp', '.h', '.hpp') and 'vendor' not in p.parts]
    files += [HERE / 'i18n.hpp']
    files += list((HERE.parent / 'pocket-game').glob('runtime.cpp'))
    files += list((HERE.parent / 'pocket-play').glob('*runtime.cpp'))
    chars = set('中文语言英语暂停继续重新开始退出保存中选择返回')
    for path in set(files):
        if not path.is_file():
            continue
        for token in TOKEN.findall(path.read_text(encoding='utf-8')):
            if token.startswith('"'):
                chars.update(c for c in token if ord(c) >= 128)
    return sorted(chars, key=ord)


def sync_assets(check=False):
    license_text = (HERE / 'OFL.txt').read_text()
    notice = ('Pocket CJK Bitmap 10\n'
              'Derived from Noto Sans CJK SC Regular.\n'
              'Copyright 2014-2021 Adobe (http://www.adobe.com/).\n'
              'Licensed under SIL Open Font License 1.1; see OFL-NotoSansCJK.txt.\n'
              'Source: https://github.com/notofonts/noto-cjk\n'
              'Modified: UI-only Unicode subset rasterized to a 10x10 monochrome\n'
              'bitmap, embedded in the game component; the derivative font is\n'
              'named Pocket CJK Bitmap 10 and remains under OFL-1.1.\n'
              'Generator: common/pocket-ui/generate_font.py (Pillow, 10px, SC face 2).\n'
              'The original hand-drawn 5x7 ASCII font remains CC0-1.0.\n')
    for name in GAMES:
        for filename, text in [('OFL-NotoSansCJK.txt', license_text), ('FONT-NOTICE.txt', notice)]:
            path = APPS / name / 'assets' / filename
            old = path.read_text() if path.exists() else None
            if old != text:
                if check:
                    raise SystemExit(f'Missing/outdated font notice: {path}')
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, default=Path('/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc'))
    parser.add_argument('--index', type=int, default=2, help='TTC face 2 is Simplified Chinese')
    parser.add_argument('--check', action='store_true', help='check glyph coverage without rewriting')
    parser.add_argument('--sync-assets', action='store_true', help='sync ten packaged font licenses; with --check, verify without writing')
    args = parser.parse_args()
    if args.sync_assets:
        sync_assets(args.check)
    chars = collect()
    out = HERE / 'glyphs.hpp'
    if args.check:
        source = out.read_text()
        missing = [c for c in chars if f'0x{ord(c):04x}u' not in source]
        if missing:
            raise SystemExit('Missing glyphs: ' + ''.join(missing))
        print(f'Covered {len(chars)} interface characters')
        return
    # Rasterize at the final grid size; Noto hinting gives clear 10px strokes.
    font = ImageFont.truetype(str(args.font), 10, index=args.index)
    lines = ['// SPDX-License-Identifier: OFL-1.1',
             '// Pocket CJK Bitmap 10; derived from Noto Sans CJK SC Regular.',
             '// Copyright 2014-2021 Adobe (http://www.adobe.com/). See OFL.txt.',
             '// Generated by generate_font.py; rows: left pixel in bit 9.',
             '#pragma once', '#include <stdint.h>', 'namespace pocket_ui {',
             'struct CjkGlyph { uint32_t codepoint; uint16_t rows[10]; };',
             'inline constexpr CjkGlyph cjk_glyphs[] = {']
    em_top = font.getbbox('国', anchor='la')[1]
    for char in chars:
        # Keep a common em box: a single horizontal stroke sits in the middle,
        # punctuation at the baseline; never top-align each character's ink.
        box = font.getbbox(char, anchor='la')
        image = Image.new('L', (10, 10))
        ImageDraw.Draw(image).text(((10-(box[2]-box[0]))//2-box[0], -em_top), char,
                                   font=font, fill=255, anchor='la')
        rows = [sum((1 << (9-x)) for x in range(10) if image.getpixel((x, y)) >= 96) for y in range(10)]
        lines.append(f'    {{0x{ord(char):04x}u, {{' + ','.join(f'0x{r:03x}' for r in rows) + f'}}}}, // {char}')
    lines += ['};', '}']
    out.write_text('\n'.join(lines)+'\n')
    print(f'Generated {len(chars)} CJK glyphs, {len(chars)*24} table bytes')


if __name__ == '__main__':
    main()
