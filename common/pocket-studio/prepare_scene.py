"""Encode a project-owned scene PNG as a bounded indexed RGB565 image."""
import argparse
from pathlib import Path
from PIL import Image
p=argparse.ArgumentParser();p.add_argument('source',type=Path);p.add_argument('output',type=Path);p.add_argument('--width',type=int,default=576);p.add_argument('--height',type=int,default=222)
a=p.parse_args()
im=Image.open(a.source).convert('RGB').resize((a.width,a.height),Image.Resampling.LANCZOS)
im=im.quantize(colors=256,dither=Image.Dither.NONE)
palette=im.getpalette();colors=[((palette[i]&248)<<8)|((palette[i+1]&252)<<3)|(palette[i+2]>>3) for i in range(0,768,3)]
lines=['// Generated by common/pocket-studio/prepare_scene.py; source: scene.png.','#include "../common/pocket-studio/studio.hpp"','namespace {','const uint16_t scene_palette[256]={'+','.join(map(str,colors))+'};','const uint8_t scene_pixels[]={']
data=im.tobytes()
lines += [','.join(map(str,data[i:i+96]))+',' for i in range(0,len(data),96)]
lines += ['};',f'const studio::Image scene_image{{{a.width},{a.height},scene_palette,scene_pixels}};','}']
a.output.write_text('\n'.join(lines)+'\n')
