"""Normalize a transparent 4x2 character atlas; reserve palette index 0 for alpha."""
import argparse
from pathlib import Path
from PIL import Image
p=argparse.ArgumentParser(description=__doc__);p.add_argument('source',type=Path);p.add_argument('png',type=Path);p.add_argument('include',type=Path);a=p.parse_args()
src=Image.open(a.source).convert('RGBA');atlas=Image.new('RGBA',(256,160))
for row in range(2):
 for col in range(4):
  tile=src.crop((col*src.width//4,row*src.height//2,(col+1)*src.width//4,(row+1)*src.height//2))
  box=tile.getchannel('A').point(lambda v:255 if v>=64 else 0).getbbox()
  if not box:raise SystemExit('empty character cell')
  tile=tile.crop(box);scale=min(54/tile.width,72/tile.height)
  tile=tile.resize((max(1,round(tile.width*scale)),max(1,round(tile.height*scale))),Image.Resampling.LANCZOS)
  atlas.alpha_composite(tile,(col*64+(64-tile.width)//2,row*80+76-tile.height))
atlas.save(a.png,optimize=True)
q=atlas.convert('RGB').quantize(colors=255,dither=Image.Dither.NONE);raw=q.tobytes();alpha=atlas.getchannel('A').tobytes();pixels=bytes(v+1 if alpha[i]>=96 else 0 for i,v in enumerate(raw));p=q.getpalette();colors=[0]+[((p[i]&248)<<8)|((p[i+1]&252)<<3)|(p[i+2]>>3) for i in range(0,765,3)]
lines=['// Generated by common/pocket-studio/prepare_sprites.py.','#include "../common/pocket-studio/studio.hpp"','namespace {','const uint16_t character_palette[256]={'+','.join(map(str,colors))+'};','const uint8_t character_pixels[]={']
lines += [','.join(map(str,pixels[i:i+96]))+',' for i in range(0,len(pixels),96)]
lines += ['};','const studio::Image cafe_characters{256,160,character_palette,character_pixels};','}'];a.include.write_text('\n'.join(lines)+'\n')
