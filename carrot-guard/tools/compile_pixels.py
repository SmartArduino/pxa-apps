#!/usr/bin/env python3
"""Compile our exported PNGs into lossless indexed scanlines for the Surface.

The original generated art remains in art/. Exported PNGs move to art/runtime/
so the package does not carry both PNG decoders' input and compiled pixels.
No colors or animation poses are removed. Transparent row margins are omitted.
"""
from pathlib import Path
from PIL import Image
import json
import struct
import zlib
import re

ROOT = Path(__file__).resolve().parents[1]


def encode(path):
    im = Image.open(path).convert('RGBA')
    colors = list(dict.fromkeys(im.getdata()))
    if len(colors) > 256:
        raise ValueError(f'{path}: expected the existing 256-color PNG export')
    indices = {color: index for index, color in enumerate(colors)}
    palette = bytearray()
    for r, g, b, a in colors:
        # Premultiply before filtering: transparent edges cannot add dark halos.
        palette.extend(struct.pack('<I', (a << 24) | ((r*a+127)//255 << 16)
                                   | ((g*a+127)//255 << 8) | (b*a+127)//255))
    palette.extend(bytes(1024 - len(palette)))
    rows, data = bytearray(), bytearray()
    for y in range(im.height):
        row = list(im.crop((0, y, im.width, y+1)).getdata())
        visible = [x for x, color in enumerate(row) if color[3]]
        left, right = (visible[0], visible[-1]+1) if visible else (0, 0)
        rows.extend(struct.pack('<IHH', len(data), left, right-left))
        data.extend(indices[color] for color in row[left:right])
    return im.size, palette + rows + data


def main():
    archive = ROOT / 'art/runtime'
    archive.mkdir(exist_ok=True)
    for path in list((ROOT / 'assets').rglob('*.png')):
        if path.name == 'icon.png':
            continue
        dest = archive / path.relative_to(ROOT / 'assets')
        dest.parent.mkdir(parents=True, exist_ok=True)
        path.replace(dest)
    bank, entries, manifest = bytearray(), [], []
    for path in sorted(archive.rglob('*.png')):
        # One complete square source per theme covers every aspect ratio.
        # The title is embedded; other themes are staged before presentation.
        if path.name.startswith('world') and '-korvo' in path.name:
            continue
        size, raw = encode(path)
        encoded = zlib.compress(raw,9)
        assert zlib.decompress(encoded) == raw
        name = 'assets/' + str(path.relative_to(archive))
        background = path.name.startswith('world')
        if background:
            assert Image.open(path).convert('RGBA').getchannel('A').getextrema()==(255,255)
        external=background and path.name!='world0.png'
        offset = 0 if external else len(bank)
        entries.append(f'{{"{name}",{size[0]},{size[1]},{offset},{len(encoded)},{len(raw)},{str(external).lower()},{str(background).lower()}}}')
        manifest.append({'path': name, 'width': size[0], 'height': size[1],
                         'stored': len(encoded), 'decoded': len(raw)})
        if external:(ROOT/'assets'/path.with_suffix('.bin').name).write_bytes(encoded)
        else:bank.extend(encoded)
    for path in (ROOT/'assets').glob('world*.bin'):
        if path.stem not in {f'world{i}' for i in range(1,6)}:path.unlink()
    header = ['// Generated by tools/compile_pixels.py; original art stays in art/.',
              '#pragma once', '#include <cstdint>', 'namespace carrot::pixels {',
              'struct Source {const char* path; uint16_t w,h; uint32_t offset,size,decoded; bool external,background;};',
              'inline constexpr Source sources[] = {', ',\n'.join(entries), '};',
              'extern const uint8_t bank[];', '}']
    (ROOT/'pixel_bank.hpp').write_text('\n'.join(header)+'\n')
    source = ['// Generated by tools/compile_pixels.py. Lossless indexed PNG pixels.',
              '#include "pixel_bank.hpp"', 'namespace carrot::pixels {', 'const uint8_t bank[] = {']
    source += [','.join(str(n) for n in bank[i:i+32])+',' for i in range(0,len(bank),32)]
    source += ['};', '}']
    (ROOT/'pixel_bank.cpp').write_text('\n'.join(source)+'\n')
    (ROOT/'art/pixel-manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
    # Position visible lettering, not its asymmetric transparent PNG margins.
    boxes={}
    def text_box(identifier,image):
        alpha=image.convert('RGBA').getchannel('A')
        # Include the antialiased outline as well as the opaque stroke. Fitting
        # only opaque pixels can leave a label's painted edge outside its box.
        bounds=alpha.getbbox()
        if bounds:
            l,t,r,b=bounds;boxes[identifier]=(l,t,r-l,b-t,image.width,image.height)
    for path in archive.rglob('*.png'):
        text_box(str(path.relative_to(archive).with_suffix('')),Image.open(path))
    for identifier,sheet,x,y,w,h in re.findall(r'\{"([^"]+)","([^"]+)",(\d+),(\d+),(\d+),(\d+),', (ROOT/'expansion_art.hpp').read_text()):
        x,y,w,h=map(int,(x,y,w,h))
        text_box(identifier,Image.open(archive/f'ui/{sheet}.png').crop((x,y,x+w,y+h)))
    (ROOT/'text_bounds.hpp').write_text('// Generated from visible ink in our exported artwork.\n#pragma once\nstruct TextBounds {const char* id;int x,y,w,h,sourceW,sourceH;};\ninline constexpr TextBounds textBounds[]={\n'+',\n'.join('{"%s",%s}'%(key,','.join(map(str,value))) for key,value in sorted(boxes.items()))+'\n};\n')
    print(f'{len(entries)} PNGs -> {len(bank)} lossless bytes; decoded only on cache misses')


if __name__ == '__main__':
    main()
