#!/usr/bin/env python3
"""Register generated carrot frames and export the actors' actual foot pivots."""
from pathlib import Path
import json
import re
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]


def export():
    original=Image.open(ROOT/'art/carrot-states-v1.png').convert('RGBA')
    cells=[]
    for row in range(4):
        for col in range(4):
            cells.append(original.crop((round(col*original.width/4),round(row*original.height/4),
                                        round((col+1)*original.width/4),round((row+1)*original.height/4))))
    boxes=[cell.getchannel('A').point(lambda a:255 if a>=32 else 0).getbbox() for cell in cells]
    assert all(boxes)
    extent=72
    scale=64/max(box[3]-box[1] for box in boxes)
    atlas=Image.new('RGBA',(extent*4,extent*4))
    for i,(cell,box) in enumerate(zip(cells,boxes)):
        pose=cell.crop(box)
        pose=pose.resize((round(pose.width*scale),round(pose.height*scale)),Image.Resampling.LANCZOS)
        atlas.alpha_composite(pose,((i%4)*extent+(extent-pose.width)//2,(i//4)*extent+68-pose.height))
    atlas.quantize(colors=256,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE).save(ROOT/'art/runtime/carrot_states.png')

    regions={}
    for name,sheet,x,y,w,h in re.findall(r'\{"([^"]+)","([^"]+)",(\d+),(\d+),(\d+),(\d+),',(ROOT/'expansion_art.hpp').read_text()):
        x,y,w,h=map(int,(x,y,w,h))
        path=ROOT/f'assets/ui/{sheet}.png'
        if not path.exists():path=ROOT/f'art/runtime/ui/{sheet}.png'
        regions[name]=Image.open(path).convert('RGBA').crop((x,y,x+w,y+h))
    def footprint(image):
        alpha=image.getchannel('A').point(lambda a:255 if a>=64 else 0)
        l,t,r,b=alpha.getbbox()
        strip=alpha.crop((0,max(t,b-max(3,round((b-t)*.16))),image.width,b))
        pixels=strip.load()
        columns=[x for x in range(strip.width) if any(pixels[x,y] for y in range(strip.height))]
        return ((columns[0]+columns[-1]+1)/2,b,columns[-1]-columns[0]+1)
    anchors=[]
    for kind,enemy in enumerate(json.loads((ROOT/'content.json').read_text())['enemies']):
        poses=[]
        for pose in range(4):
            if kind<4:
                image=regions[f'walk{pose}' if kind==0 else enemy['sprite']]
            else:
                path=ROOT/f'assets/{enemy["sprite"]}.png'
                if not path.exists():path=ROOT/f'art/runtime/{enemy["sprite"]}.png'
                strip=Image.open(path).convert('RGBA')
                size=strip.height
                image=strip.crop((pose*size,0,(pose+1)*size,size))
            x,y,width=footprint(image)
            poses.append('{%.6ff,%.6ff,%.6ff}'%(x/image.width,y/image.height,width/image.width))
        anchors.append('{'+','.join(poses)+'}')
    (ROOT/'actor_layout.hpp').write_text('// Generated by tools/import_actor_states.py; normalized foot contact pivots.\n#pragma once\nstruct ActorFoot {float x,y,width;};\ninline constexpr ActorFoot actorFeet[][4]={\n'+',\n'.join(anchors)+'\n};\n')
    print('Registered 16 carrot frames and foot pivots for 15 monster species')


if __name__=='__main__':export()
