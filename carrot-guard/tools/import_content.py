#!/usr/bin/env python3
"""Compile the maintained campaign data into allocation-free C++ tables."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]


def export():
    data = json.loads((ROOT / 'content.json').read_text())
    maps = json.loads((ROOT / 'maps.json').read_text())['maps']
    towers, enemies, levels = (data[k] for k in ('towers', 'enemies', 'levels'))
    assert len(towers) == 6 and len(levels) == 18
    assert all(0 <= level['map'] < len(maps) for level in levels)
    assert all(0 <= level['theme'] < len(data['themes']) for level in levels)
    def number(v):
        return f'{float(v):.4f}f'
    header = ['// Generated by tools/import_content.py from content.json.',
        '#pragma once', 'namespace carrot {',
        f'inline constexpr int Levels={len(levels)}, TowerTypes={len(towers)}, EnemyTypes={len(enemies)}, Themes={len(data["themes"])};',
        'enum class Mission { Standard, Treasure, Swarm, Armor, Boss, Rush, Timed };',
        'struct TowerDef { const char *icon,*label; int cost,upgrade,unlock; float damage,cooldown,range; unsigned color; };',
        'inline constexpr TowerDef towerDefs[]={ {"","",0,0,0,0,0,0,0},']
    for t in towers:
        header.append('{"%s","%s",%d,%d,%d,%s,%s,%s,0x%06x},' % (
            t['icon'], t['label'], t['cost'], t['upgrade'], t['unlock'],
            number(t['damage']), number(t['cooldown']), number(t['range']), t['color']))
    header += ['};', 'inline constexpr int costs[]={0,' + ','.join(str(t['cost']) for t in towers) + '};',
        'inline constexpr int upgrades[]={0,' + ','.join(str(t['upgrade']) for t in towers) + '};',
        'struct EnemyDef { const char *sprite; float hp,speed; int reward; float armor; bool boss,facesRight; };',
        'inline constexpr EnemyDef enemyDefs[]={']
    for e in enemies:
        header.append('{"%s",%s,%s,%d,%s,%s,%s},' % (e['sprite'], number(e['hp']), number(e['speed']), e['reward'], number(e['armor']), str(e['boss']).lower(),str(e.get('faces_right',True)).lower()))
    header += ['};', 'struct LevelDef { int map,theme; Mission mission; int waves,coins,boss,timeLimit,chests,pool[9],poolCount; };',
        'inline constexpr LevelDef levelDefs[]={']
    modes = ['Standard', 'Treasure', 'Swarm', 'Armor', 'Boss', 'Rush', 'Timed']
    for level in levels:
        pool = ','.join(str(v) for v in level['enemy_pool'])
        header.append('{%d,%d,Mission::%s,%d,%d,%d,%d,%d,{%s},%d},' % (
            level['map'], level['theme'], modes[level['mode']], level['waves'], level['coins'],
            level['boss'], level['time_limit'], level['chests'], pool, len(level['enemy_pool'])))
    header += ['};', '} // namespace carrot']
    (ROOT / 'content.hpp').write_text('\n'.join(header) + '\n')


if __name__ == '__main__':
    export()
