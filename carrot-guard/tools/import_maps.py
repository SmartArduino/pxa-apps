#!/usr/bin/env python3
"""Generate road artwork and C++ occupancy from the same tile map source."""
import json
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]


def load_maps():
    data = json.loads((ROOT / 'maps.json').read_text())
    g = data['grid']
    base, columns, rows, cell, oy = (g[k] for k in
        ('base_columns', 'max_columns', 'rows', 'cell_size', 'origin_y'))
    assert base % 2 == columns % 2 == 1 and base <= columns <= 31
    shift = (columns - base) // 2
    for m in data['maps']:
        assert 2 <= len(m['path']) <= 12 and len(m['anchors']) == 12
        road = set()
        for a, b in zip(m['path'], m['path'][1:]):
            assert (a[0] == b[0]) != (a[1] == b[1]), 'Axis-aligned tile route required'
            dx, dy = (b[0] > a[0]) - (b[0] < a[0]), (b[1] > a[1]) - (b[1] < a[1])
            length = abs(b[0] - a[0]) + abs(b[1] - a[1])
            for n in range(length + 1):
                c, r = a[0] + n * dx, a[1] + n * dy
                assert 0 <= c < base and 0 <= r < rows
                road.add((c, r))
        start_c, start_r = m['path'][0]
        assert start_r > 0
        blocked = road | {(start_c, start_r - 1)}
        m['road_cells'] = sorted(road)
        m['blocked'] = [sum(1 << (c + shift) for c, rr in blocked if rr == r)
                        for r in range(rows)]
        m['points'] = [[c * cell + cell // 2, oy + r * cell + cell // 2]
                       for c, r in m['path']]
        m['anchor_points'] = [[c * cell + cell // 2, oy + r * cell + cell // 2]
                              for c, r in m['anchors']]
    return data


def export():
    data = load_maps()
    g = data['grid']
    base, columns, rows, cell, oy = (g[k] for k in
        ('base_columns', 'max_columns', 'rows', 'cell_size', 'origin_y'))
    themes = json.loads((ROOT / 'content.json').read_text())['themes']
    header = ['// Generated by tools/import_maps.py from maps.json.\n#pragma once\n#include <cstdint>\nnamespace carrot {',
        f'inline constexpr int BaseGridColumns={base}, GridColumns={columns}, GridRows={rows}, CellSize={cell}, GridOriginY={oy};',
        'inline constexpr int GridOriginX=-(GridColumns-BaseGridColumns)/2*CellSize;',
        'inline constexpr int WorldWidth=BaseGridColumns*CellSize, WorldHeight=GridRows*CellSize+2*GridOriginY;',
        'struct Point { float x,y; };',
        'struct Map { Point path[12]; int count; Point anchors[12]; uint32_t blocked[GridRows]; };',
        'inline constexpr Map maps[]={']
    for index, m in enumerate(data['maps']):
        points = ','.join('{%d,%d}' % tuple(p) for p in m['points'])
        anchors = ','.join('{%d,%d}' % tuple(p) for p in m['anchor_points'])
        mask = ','.join('0x%08xU' % value for value in m['blocked'])
        header.append('{ {'+points+'},'+str(len(m['points']))+', {'+anchors+'}, {'+mask+'} },')
        # One tile wide, with the border contained in its reserved cells.
        image = Image.new('RGBA', ((base + 2) * cell * 2, (rows * cell + oy * 2) * 2))
        draw = ImageDraw.Draw(image)
        coords = [((x + cell) * 2, y * 2) for x, y in m['points']]
        palette = themes[m.get('theme', 0)]['road']
        for width, color in zip((cell*2, cell*2-4, cell*2-10, cell*2-18), palette):
            draw.line(coords, fill=color, width=width, joint='curve')
            for x, y in coords:
                radius = width // 2
                draw.ellipse((x-radius,y-radius,x+radius-1,y+radius-1),fill=color)
        for a, b in zip(coords, coords[1:]):
            length = abs(b[0]-a[0])+abs(b[1]-a[1])
            for n in range(cell, length, cell*2):
                t = n / length
                x, y = a[0]+(b[0]-a[0])*t, a[1]+(b[1]-a[1])*t
                draw.ellipse((x-3,y-2,x+3,y+1),fill='#e9bd76')
        image.resize(((base+2)*cell, rows*cell+oy*2), Image.Resampling.LANCZOS).save(
            ROOT / 'assets' / f'scene{index}.png', optimize=True)
    header += ['};', '} // namespace carrot']
    (ROOT / 'map_data.hpp').write_text('\n'.join(header)+'\n')
    print('Generated tile-aligned roads and identical C++ occupancy masks')


if __name__ == '__main__':
    export()
