"""Convert the pinned dsh-pet WebM clips to bounded keyframe and delta groups.

Requires ffmpeg with libvpx-vp9, Pillow and zopfli 0.4.0. Run after updating the submodule.
Video decoding happens only in this offline tool. Generated art retains the
upstream noncommercial license described in assets/NOTICE.txt.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import zlib
import zopfli.zlib

from PIL import Image

APP = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT, FPS = 192, 144, 12
KEYFRAME_INTERVAL = 12


def convert(upstream):
    clips = json.loads((APP / "clips.json").read_text())
    assets = APP / "assets"
    assets.mkdir(exist_ok=True)
    headers = ['// Generated by tools/prepare_assets.py. Artwork is CC BY-NC-SA 4.0.',
               '#pragma once', '#include <stdint.h>', 'namespace fish::art {',
               'enum Clip : unsigned { ' + ', '.join(c[0] for c in clips) + ', COUNT };',
               f'constexpr unsigned WIDTH = {WIDTH}, HEIGHT = {HEIGHT}, FPS = {FPS};',
               'struct Frame { uint32_t offset, bytes; uint16_t key; bool delta; };',
               'struct Animation { const char *en, *zh; uint16_t first, count; const uint16_t *palette; };']
    frames, animations, sources = [], [], []
    binary = bytearray()
    posters = ['// Generated by tools/prepare_assets.py. Artwork is CC BY-NC-SA 4.0.',
               '#pragma once', '#include <stdint.h>', 'namespace fish::art {']
    for index, (symbol, name, en, zh) in enumerate(clips):
        path = upstream / 'dsh-pet/assets/webm' / (name + '.webm')
        # libvpx is selected explicitly because ffmpeg's native VP9 decoder
        # drops the alpha plane. A fixed crop preserves each animation's anchor.
        command = ['ffmpeg', '-v', 'error', '-threads', '1', '-c:v', 'libvpx-vp9',
                   '-i', str(path), '-vf',
                   f'fps={FPS},crop=480:360:80:0,scale={WIDTH}:{HEIGHT}:flags=lanczos',
                   '-t', '30', '-f', 'rawvideo', '-pix_fmt', 'rgba', 'pipe:1']
        raw = subprocess.run(command, check=True, capture_output=True).stdout
        frame_bytes = WIDTH * HEIGHT * 4
        if not raw or len(raw) % frame_bytes:
            raise ValueError(f'Invalid decoded clip {path}')
        images = [Image.frombytes('RGBA', (WIDTH, HEIGHT), raw[at:at+frame_bytes])
                  for at in range(0, len(raw), frame_bytes)]
        if all(im.getchannel('A').getextrema() == (255, 255) for im in images):
            raise ValueError(f'Alpha channel missing in {path}')
        # One stable palette per clip avoids temporal color flicker.
        samples = images[::max(1, len(images) // 16)]
        sheet = Image.new('RGB', (WIDTH, HEIGHT * len(samples)), '#accbdc')
        for row, im in enumerate(samples):
            sheet.paste(im, (0, row * HEIGHT), im)
        quantized = sheet.quantize(colors=255, dither=Image.Dither.NONE)
        palette = quantized.getpalette()[:765]
        words = [0] + [((palette[i] & 248) << 8) | ((palette[i+1] & 252) << 3)
                       | (palette[i+2] >> 3) for i in range(0, 765, 3)]
        # RGB565 can merge palette colors. Canonical indices preserve its exact output.
        remap = bytes([0] + [words.index(word, 1) for word in words[1:]])
        headers.append(f'inline constexpr uint16_t palette_{index}[256] = {{' + ','.join(map(str, words)) + '};')
        first = len(frames)
        previous = None
        keyframe = first
        for frame_number, im in enumerate(images):
            q = im.convert('RGB').quantize(palette=quantized, dither=Image.Dither.NONE)
            alpha = im.getchannel('A').tobytes()
            pixels = bytes(v + 1 if alpha[i] >= 96 else 0 for i, v in enumerate(q.tobytes()))
            indices = pixels.translate(remap)
            packed = min(zlib.compress(indices, level=9),
                         zopfli.zlib.compress(indices, numiterations=5), key=len)
            delta = False
            if frame_number % KEYFRAME_INTERVAL and previous is not None:
                difference = bytes((a - b) & 255 for a, b in zip(indices, previous))
                candidate = zlib.compress(difference, level=9)
                if len(candidate) < len(packed):
                    packed, delta = candidate, True
            if not delta:
                keyframe = len(frames)
            if frame_number == 0 and symbol in ('IDLE', 'SLEEP'):
                posters.append(f'inline constexpr uint8_t poster_{symbol.lower()}[] = {{' +
                               ','.join(map(str, packed)) + '};')
            if len(packed) > 32768:
                raise ValueError('Frame exceeds the runtime staging buffer')
            frames.append((len(binary), len(packed), keyframe, int(delta)))
            binary.extend(packed)
            previous = indices
        animations.append((en, zh, first, len(images), index))
        sources.append({'clip': symbol, 'source': str(path.relative_to(upstream)),
                        'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                        'frames': len(images)})
        print(f'{symbol}: {len(images)} frames, {len(binary)} bytes total', flush=True)
    headers.append('inline constexpr Frame frames[] = {')
    headers.extend(f'{{{offset},{size},{key},{delta}}},' for offset, size, key, delta in frames)
    headers.append('};\ninline constexpr Animation animations[] = {')
    headers.extend(f'{{{json.dumps(en)},{json.dumps(zh, ensure_ascii=False)},{first},{count},palette_{index}}},'
                   for en, zh, first, count, index in animations)
    headers.append('};\n} // namespace fish::art\n')
    (APP / 'animation_data.hpp').write_text('\n'.join(headers))
    (APP / 'startup_frames.inc').write_text('\n'.join(posters) + '\n}\n')
    (assets / 'animations.bin').write_bytes(binary)
    commit = subprocess.check_output(['git', '-C', str(upstream), 'rev-parse', 'HEAD'], text=True).strip()
    (assets / 'sources.json').write_text(json.dumps({
        'repository': 'https://github.com/PC2005-cloud/dsh-pet', 'commit': commit,
        'license': 'CC-BY-NC-SA-4.0', 'size': [WIDTH, HEIGHT], 'fps': FPS,
        'codec': 'zlib-deflate-delta', 'palette_indices': 'canonical-rgb565',
        'encoder': 'zopfli-0.4.0', 'encoder_iterations': 5,
        'delta': 'uint8-subtract', 'keyframe_interval': KEYFRAME_INTERVAL,
        'clips': sources, 'sha256': hashlib.sha256(binary).hexdigest()
    }, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream', type=Path, default=APP / 'vendor/dsh-pet')
    convert(parser.parse_args().upstream.resolve())
