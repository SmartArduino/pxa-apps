"""Bake the four generated materials into packed 4-bit indexed textures."""
from pathlib import Path

from PIL import Image

app = Path(__file__).resolve().parent.parent
source = Image.open(app / 'art/generated/terrain-campaign-v1.png').convert('RGB')
size = 128


def rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def array(values):
    return '{' + ','.join(map(str, values)) + '}'


pixels, palettes, shadows = [], [], []
for row in range(2):
    for col in range(2):
        width, height = source.size
        tile = source.crop((col * width // 2 + 3, row * height // 2 + 3,
                            (col + 1) * width // 2 - 3, (row + 1) * height // 2 - 3))
        tile = tile.resize((size, size), Image.Resampling.BOX).quantize(colors=16, dither=Image.Dither.NONE)
        texels = tile.tobytes()
        pixels.extend(a | b << 4 for a, b in zip(texels[::2], texels[1::2]))
        rgb = tile.getpalette()
        palettes.append(array(rgb565(*rgb[i:i + 3]) for i in range(0, 48, 3)))
        shadows.append(array(rgb565(*((7 * a + 9 * b) // 16 for a, b in zip(rgb[i:i + 3], (12, 23, 29))))
                             for i in range(0, 48, 3)))

header = """// Generated by tools/generate_campaign_terrain.py from terrain-campaign-v1.png.
#pragma once
#include <array>
#include <cstdint>
namespace iron::art {
"""
header += f"inline constexpr std::array<uint8_t,{len(pixels)}> campaign_texels={{\n"
header += ',\n'.join(','.join(map(str, pixels[i:i + 64])) for i in range(0, len(pixels), 64)) + '\n};\n'
for name, data in [('campaign_material', palettes), ('campaign_material_dim', shadows)]:
    header += f'inline constexpr uint16_t {name}[4][16]=' + array(data) + ';\n'
(app / 'campaign_terrain_data.hpp').write_text(header + '}\n')
