"""Rebuild the original icon and a small 2-bit subset of the OFL system font."""
from pathlib import Path
import hashlib
from PIL import Image,ImageDraw,ImageFont
import cairosvg
app=Path(__file__).resolve().parents[1]
workspace=app.parents[2]
font=workspace/'factory/base/system/fonts/noto_sans_cjk_common.ttf'
face=ImageFont.truetype(str(font),20)
source=''.join(p.read_text() for p in app.glob('*.hpp') if p.name!='font.hpp')+(app/'main.cpp').read_text()
chars=sorted(set(chr(i) for i in range(32,127))|{c for c in source if ord(c)>127})
data=[];adv=[]
for c in chars:
 im=Image.new('L',(24,28));d=ImageDraw.Draw(im);d.text((0,0),c,font=face,fill=255)
 pixels=list(im.getdata());data.extend(sum(((min(3,(pixels[i+j]*3+127)//255))<<(j*2)) for j in range(4)) for i in range(0,len(pixels),4));adv.append(round(face.getlength(c)))
header='// Generated by tools/generate_assets.py; font: SIL OFL 1.1.\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace iron {\n'
header+=f'inline constexpr std::array<uint32_t,{len(chars)}> glyph_codes={{'+','.join(str(ord(c)) for c in chars)+'};\n'
header+=f'inline constexpr std::array<uint8_t,{len(chars)}> glyph_width={{'+','.join(map(str,adv))+'};\n'
header+=f'inline constexpr std::array<uint8_t,{len(data)}> glyph_bits={{'+','.join(map(str,data))+'};\n}\n'
(app/'font.hpp').write_text(header)
cairosvg.svg2png(url=str(app/'art/icon.svg'),write_to=str(app/'assets/icon.png'),output_width=96,output_height=96)
common=app.parent/'common/motion-games/licenses'
notice='Iron Dawn: original application code, game rules and procedural artwork: MIT.\nFont subset: Noto Sans CJK, SIL OFL 1.1.\nFont SHA256: '+hashlib.sha256(font.read_bytes()).hexdigest()+'\n\n'
for name in ('PXA-SDK-LICENSE.txt','FONT-NOTICE','FONT-OFL.txt','FONT-OFL-Latin.txt'):
 notice+='=== '+name+' ===\n'+(common/name).read_text()+'\n'
(app/'assets/NOTICE.txt').write_text(notice)
print(len(chars),'glyphs;',len(data),'font bytes')
