#!/usr/bin/env python3
"""Turn selected generated masters into bounded resident effects and music."""
from pathlib import Path
import argparse,hashlib,json,subprocess
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
RATE=16000

def decode(path):
    raw=subprocess.check_output(['ffmpeg','-v','error','-i',str(path),'-ac','1','-ar',str(RATE),'-f','f32le','-'])
    samples=np.frombuffer(raw,dtype='<f4').copy();return samples-samples.mean()

def encode(path,samples):
    path.parent.mkdir(parents=True,exist_ok=True)
    subprocess.run(['ffmpeg','-v','error','-y','-f','f32le','-ar',str(RATE),'-ac','1','-i','-','-c:a','flac','-sample_fmt','s16',str(path)],input=samples.astype('<f4').tobytes(),check=True)

def metrics(path,samples):
    return dict(duration=len(samples)/RATE,bytes=path.stat().st_size,sha256=hashlib.sha256(path.read_bytes()).hexdigest(),peak=float(abs(samples).max()),rms=float(np.sqrt(np.mean(samples*samples))))

def main():
    p=argparse.ArgumentParser();p.add_argument('--source',required=True,type=Path);p.add_argument('--report',required=True,type=Path);args=p.parse_args()
    config_path=ROOT/'tools/audio-prompts.json';config=json.loads(config_path.read_text())
    target=ROOT/'assets/audio';target.mkdir(parents=True,exist_ok=True)
    report={};names=list(config['effects']);sizes=[];lengths=[]
    for name,spec in config['effects'].items():
        samples=decode(args.source/(name+'.flac'))
        n=len(samples)//160;env=np.sqrt(np.mean(samples[:n*160].reshape(-1,160)**2,axis=1));peak=int(np.argmax(env));onset=peak
        while onset>0 and (env[max(0,onset-3):onset]>env[peak]*.1).any():onset-=1
        start=max(0,onset*160-64);limit=min(.95,spec['maximum_seconds'])
        clip=samples[start:start+round(limit*RATE)].copy()
        clip*=min(.82/max(1e-9,max(abs(clip))),.26/max(1e-9,float(np.sqrt(np.mean(clip*clip)))))
        clip[:16]*=np.linspace(0,1,16);fade=min(480,len(clip)//4);clip[-fade:]*=np.linspace(1,0,fade)
        master=ROOT/'art/audio'/f'{name}.flac';encode(master,clip)
        path=target/(name+'.pcm');path.write_bytes(np.clip(np.rint(clip*127+128),0,255).astype('u1').tobytes())
        report[name]=dict(metrics(path,clip),source_start=start/RATE,master_sha256=hashlib.sha256(master.read_bytes()).hexdigest());sizes.append(path.stat().st_size);lengths.append(round(len(clip)*1000/RATE))
    for name,spec in config['music'].items():
        samples=decode(args.source/(name+'.flac'))
        if spec['loop']:
            beat=60/spec['bpm'];length=round(64*beat*RATE);fade=round(4*beat*RATE);start=round(4*RATE)
            section=samples[start:start+length+fade];assert len(section)==length+fade,name
            weight=np.linspace(0,1,fade)
            clip=np.concatenate([section[fade:length],section[length:]*(1-weight)+section[:fade]*weight])
        else:
            clip=samples.copy();clip[:160]*=np.linspace(0,1,160);clip[-800:]*=np.linspace(1,0,800)
        clip*=min(.68/max(1e-9,max(abs(clip))),.13/max(1e-9,float(np.sqrt(np.mean(clip*clip)))))
        master=ROOT/'art/audio'/f'{name}.flac';encode(master,clip)
        path=target/(name+'.ogg');subprocess.run(['ffmpeg','-v','error','-y','-i',str(master),'-c:a','libvorbis','-q:a','4',str(path)],check=True)
        report[name]=dict(metrics(path,clip),loop=spec['loop'],master_sha256=hashlib.sha256(master.read_bytes()).hexdigest())
    enum=', '.join('throw_hit' if n=='throw' else n for n in names)
    text='// Generated by tools/prepare_audio.py.\n#pragma once\n#include <cstdint>\nnamespace ash::audio {\n'
    text+='enum class Sfx:unsigned {'+enum+', count};\n'
    text+='inline constexpr const char* sfx_files[]={'+','.join(json.dumps(n+'.pcm') for n in names)+'};\n'
    text+='inline constexpr unsigned sfx_bytes[]={'+','.join(map(str,sizes))+'};\n'
    text+='inline constexpr unsigned sfx_ms[]={'+','.join(map(str,lengths))+'};\n}\n'
    (ROOT/'audio_data.hpp').write_text(text)
    config['processed']={name:{k:v for k,v in details.items() if k in ['sha256','master_sha256','duration','bytes']} for name,details in report.items()}
    config_path.write_text(json.dumps(config,indent=2,ensure_ascii=False)+'\n');args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(report,indent=2)+'\n')
    print('Prepared',len(names),'effects and',len(config['music']),'music tracks')

if __name__=='__main__':main()
