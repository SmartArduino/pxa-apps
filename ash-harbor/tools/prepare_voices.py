#!/usr/bin/env python3
"""Trim original character performances and prepare direct-play voice assets."""
from pathlib import Path
import argparse,hashlib,json,shutil,subprocess
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
RATE=16000

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--source',required=True,type=Path);parser.add_argument('--report',required=True,type=Path);args=parser.parse_args()
    config_path=ROOT/'tools/voice-prompts.json';config=json.loads(config_path.read_text())
    # Refuse a mismatched casting import before replacing any runtime files.
    for cast in config['cast']:
        reference=args.source/(cast['id']+'-reference.flac')
        if 'selection' in cast:
            assert hashlib.sha256(reference.read_bytes()).hexdigest()==cast['selection']['sha256'],(cast['id'],'Selected voice reference changed')
        for cue in cast['lines']:assert (args.source/(cast['id']+'-'+cue+'.flac')).is_file(),(cast['id'],cue)
    target=ROOT/'assets/audio/voices';masters=ROOT/'art/audio/voices'
    target.mkdir(parents=True,exist_ok=True);masters.mkdir(parents=True,exist_ok=True)
    report={};names=[];sizes=[];lengths=[];cues=list(config['cast'][0]['lines'])
    for cast in config['cast']:
        shutil.copyfile(args.source/(cast['id']+'-reference.flac'),masters/(cast['id']+'-reference.flac'))
        row=[];row_sizes=[];row_lengths=[]
        for cue,text in cast['lines'].items():
            name=cast['id']+'-'+cue;source=args.source/(name+'.flac')
            raw=subprocess.check_output(['ffmpeg','-v','error','-i',str(source),'-ac','1','-ar',str(RATE),'-af','highpass=f=90,lowpass=f=7200','-f','f32le','-'])
            samples=np.frombuffer(raw,dtype='<f4').copy()
            # Select a complete take before trimming silence; keep the source untouched.
            window=cast.get('source_windows',{}).get(cue,[0,len(samples)/RATE])
            offset=round(window[0]*RATE);limit=round(window[1]*RATE)
            assert 0<=offset<limit<=len(samples),(name,window)
            samples=samples[offset:limit]
            n=len(samples)//160;env=np.sqrt(np.mean(samples[:n*160].reshape(-1,160)**2,axis=1))
            active=np.flatnonzero(env>max(.001,float(env.max())*.025));assert len(active),name
            nonverbal=cue in cast.get('nonverbal_limits',{})
            if nonverbal and not config.get('complete_nonverbal_takes',False):
                peak=int(np.argmax(env));onset=peak
                while onset>0 and (env[max(0,onset-3):onset]>env[peak]*.1).any():onset-=1
                begin=max(0,onset*160-48);end=min(len(samples),begin+round(min(.95,cast['nonverbal_limits'][cue])*RATE))
            else:begin=max(0,int(active[0])*160-400);end=min(len(samples),(int(active[-1])+1)*160+960)
            if nonverbal and config.get('complete_nonverbal_takes',False):
                assert (end-begin)/RATE<=cast['nonverbal_limits'][cue],(name,'Regenerate an overlong take; do not cut the performance',(end-begin)/RATE)
            clip=samples[begin:end];clip-=clip.mean();clip*=min(.82/max(1e-9,max(abs(clip))),.21/max(1e-9,float(np.sqrt(np.mean(clip*clip)))))
            clip[:48]*=np.linspace(0,1,48);clip[-128:]*=np.linspace(1,0,128)
            assert (.08 if nonverbal else .15)<len(clip)/RATE<4.5,(name,len(clip)/RATE)
            use_u8=nonverbal and config.get('runtime_encoding')!='s16le'
            suffix='.pcm' if use_u8 else '.s16';encoding='u8' if use_u8 else 's16le'
            path=target/(name+suffix)
            pcm=np.clip(np.rint(clip*127+128),0,255).astype('u1') if use_u8 else np.clip(np.rint(clip*32767),-32768,32767).astype('<i2')
            path.write_bytes(pcm.tobytes())
            master=masters/(name+'.flac');subprocess.run(['ffmpeg','-v','error','-y','-f',encoding,'-ar',str(RATE),'-ac','1','-i',str(path),'-c:a','flac',str(master)],check=True)
            report[name]={'text':text,'seconds':len(clip)/RATE,'bytes':path.stat().st_size,'runtime_file':path.name,'encoding':encoding,'source_model':cast.get('nonverbal_model','Stable Audio 3 Small SFX') if nonverbal else 'Qwen3-TTS Base' if 'base' in config['models'] else 'Qwen3-TTS CustomVoice','sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'master_sha256':hashlib.sha256(master.read_bytes()).hexdigest(),'trim':[(offset+begin)/RATE,(offset+end)/RATE]}
            row.append(name+suffix);row_sizes.append(path.stat().st_size);row_lengths.append(round(len(clip)*1000/RATE))
        names.append(row);sizes.append(row_sizes);lengths.append(row_lengths)
    header='// Generated by tools/prepare_voices.py.\n#pragma once\nnamespace ash::audio {\n'
    header+='enum class Voice:unsigned {'+','.join('throw_move' if n=='throw' else n for n in cues)+',count};\n'
    header+='inline constexpr const char* voice_files['+str(len(names))+']['+str(len(cues))+']={'+','.join('{'+','.join(json.dumps(n) for n in row)+'}' for row in names)+'};\n'
    for field,rows in [('voice_bytes',sizes),('voice_ms',lengths)]:header+='inline constexpr unsigned '+field+'['+str(len(names))+']['+str(len(cues))+']={'+','.join('{'+','.join(map(str,row))+'}' for row in rows)+'};\n'
    header+='}\n';(ROOT/'voice_data.hpp').write_text(header)
    selected={name for row in names for name in row}
    for path in target.iterdir():
        if path.is_file() and path.name not in selected:path.unlink()
    config['processed']=report;config['model_sha256']=json.loads((args.source/'model-hashes.json').read_text());config_path.write_text(json.dumps(config,indent=2,ensure_ascii=False)+'\n')
    args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n');print('Prepared',len(report),'original character clips')

if __name__=='__main__':main()
