#!/usr/bin/env python3
"""Embed lossless byte-run atlas banks, avoiding per-frame filesystem requests."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
def encode(raw):
 out=bytearray();i=0
 while i<len(raw):
  run=1
  while i+run<len(raw) and raw[i+run]==raw[i] and run<128:run+=1
  if run>=3:out.extend((128+run-1,raw[i]));i+=run;continue
  begin=i;i+=run
  while i<len(raw) and i-begin<128:
   run=1
   while i+run<len(raw) and raw[i+run]==raw[i] and run<128:run+=1
   if run>=3:break
   i+=min(run,128-(i-begin))
  out.append(i-begin-1);out.extend(raw[begin:i])
 return out
def prepare():
 resources=json.loads((ROOT/'resources.json').read_text())['assets']
 import re
 static=int(re.search(r'static_pages=(\d+)',(ROOT/'art.hpp').read_text()).group(1))
 bank=bytearray();offsets=[];lengths=[]
 for i,r in enumerate(resources):
  raw=(ROOT/r['source']).read_bytes();assert len(raw)==r['width']*r['height']
  offsets.append(len(bank));compressed=encode(raw);lengths.append(len(compressed));bank.extend(compressed)
 (ROOT/'assets/frame-pixels.bin').unlink(missing_ok=True)
 old=ROOT/'assets/frames'
 if old.exists():
  for path in old.glob('atlas-*.bin'):path.unlink()
  old.rmdir()
 (ROOT/'art/frame-cache-rle.bin').write_bytes(bank)
 text='// Generated by tools/prepare_frame_cache.py; lossless original atlas pixels.\n#pragma once\nnamespace ash::art {\n'
 for name,values in [('page_width',[r['width'] for r in resources]),('page_height',[r['height'] for r in resources]),('page_offset',offsets),('page_rle_bytes',lengths)]:text+='inline constexpr unsigned '+name+'[]={'+','.join(map(str,values))+'};\n'
 text+='inline constexpr char frame_rle[]=\n'+''.join('"'+''.join(f'\\x{v:02x}' for v in bank[i:i+128])+'"\n' for i in range(0,len(bank),128))+';\n}\n'
 (ROOT/'frame_dimensions.hpp').write_text(text)
 print('Embedded lossless atlases:',len(resources),'encoded bytes',len(bank),'decoded bytes',sum(r['width']*r['height'] for r in resources))
if __name__=='__main__':prepare()
