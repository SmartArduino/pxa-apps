"""Pack the existing attributed RGB565 sprites without color quantization."""
from pathlib import Path
import re
from building_art import SOURCE_ONLY
ROOT=Path(__file__).resolve().parents[1]
def shade(c,l):return ((((c>>11)&31)*l//255)<<11)|((((c>>5)&63)*l//255)<<5)|((c&31)*l//255)
def tint(c,t):return ((((c>>11)&31)*((t>>11)&31)//31)<<11)|((((c>>5)&63)*((t>>5)&63)//63)<<5)|((c&31)*(t&31)//31)
def rgb(r,g,b):return ((r&248)<<8)|((g&252)<<3)|(b>>3)
def main():
 source=(ROOT/'art.hpp').read_text();arrays={n:[int(x,0) for x in s.split(',') if x] for n,s in re.findall(r'inline constexpr uint32_t (\w+)_pixels\[\]=\{([^}]+)\};',source)}
 sprites=[(n,int(w),int(h),arrays[n]) for n,w,h in re.findall(r'inline constexpr Sprite (\w+)\{(\d+),(\d+),\w+_pixels\};',source)]
 # Runtime draws the precomposed drill frames; source layers stay in art.hpp
 # for the legacy renderer and provenance, rather than occupying atlas space.
 source_only=SOURCE_ONLY
 sprites=[s for s in sprites if s[0] not in source_only]
 colors={c&65535 for _,_,_,data in sprites for c in data if c>>16}
 for n,w,h,data in sprites:
  levels=[110,205] if n in ['stone1','stone2','stone3','sand1','water','snow'] else [110,235] if n in ['copper','lead','coal','titanium'] else [100,210] if n=='rock' else []
  for light in levels:colors.update(shade(c&65535,light) for c in data if c>>16)
 colors.update(rgb(*c) for c in [(55,81,119),(32,33,39),(146,104,67),(83,83,90),(255,211,127),(23,24,28)])
 palette=[0]+sorted(colors);assert len(palette)<=256,len(palette);lookup={c:i for i,c in enumerate(palette) if i}
 palette.extend([0]*(256-len(palette)))
 atlas=[0]*65536;entries=[]
 free=[(0,0,256,256)]
 for n,w,h,data in sorted(sprites,key=lambda s:(-s[2],-s[1],s[0])):
  choices=[(min(fw-w,fh-h),max(fw-w,fh-h),fy,fx) for fx,fy,fw,fh in free if w<=fw and h<=fh]
  assert choices,('Atlas full',n,w,h)
  _,_,y,x=min(choices)
  remaining=[]
  for fx,fy,fw,fh in free:
   if x>=fx+fw or x+w<=fx or y>=fy+fh or y+h<=fy:remaining.append((fx,fy,fw,fh));continue
   if x>fx:remaining.append((fx,fy,x-fx,fh))
   if x+w<fx+fw:remaining.append((x+w,fy,fx+fw-x-w,fh))
   if y>fy:remaining.append((fx,fy,fw,y-fy))
   if y+h<fy+fh:remaining.append((fx,y+h,fw,fy+fh-y-h))
  free=[]
  for rect in dict.fromkeys(remaining):
   fx,fy,fw,fh=rect
   if not any(other!=rect and ox<=fx and oy<=fy and ox+ow>=fx+fw and oy+oh>=fy+fh for other in remaining for ox,oy,ow,oh in [other]):free.append(rect)
  for yy in range(h):
   for xx in range(w):
    c=data[yy*w+xx];atlas[(y+yy)*256+x+xx]=lookup[c&65535] if c>>16 else 0
  entries.append((n,x,y,w,h))
 out=['// Generated by tools/build_render_assets.py. Original assets: GPL-3.0.','#pragma once','#include "art.hpp"','namespace md_art {','struct Region {const art::Sprite *sprite;unsigned short x,y,w,h;};','inline constexpr Region regions[]={']
 for n,x,y,w,h in entries:out.append('{'+('&art::'+n)+f',{x},{y},{w},{h}'+'},')
 out+=['};','inline constexpr unsigned short palette[256]={'+','.join(map(str,palette))+'};','inline constexpr unsigned char atlas[65536]={'+','.join(map(str,atlas))+'};','}']
 (ROOT/'render_assets.hpp').write_text('\n'.join(out)+'\n');print('Atlas: 256x256;',len(colors),'exact RGB565 colors;',len(entries),'regions')
if __name__=='__main__':main()
