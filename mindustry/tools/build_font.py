"""Bake all known UI characters from the attributed OFL system font (Pillow).
Only generated glyph metrics/PackBits enter the executable; no runtime font I/O.
"""
import hashlib,json
from pathlib import Path
from PIL import ImageFont
ROOT=Path(__file__).resolve().parents[1]
FONT=ROOT/'font-source/noto_sans_cjk_common.ttf'

def pack(data):
 out=bytearray();i=0
 while i<len(data):
  run=1
  while i+run<len(data) and data[i+run]==data[i] and run<128:run+=1
  if run>=3:out.extend((128+run-1,data[i]));i+=run;continue
  start=i;i+=run
  while i<len(data) and i-start<128:
   run=1
   while i+run<len(data) and data[i+run]==data[i] and run<3:run+=1
   if run>=3:break
   i+=min(run,128-(i-start))
  out.append(i-start-1);out.extend(data[start:i])
 return out

def main():
 assert hashlib.sha256(FONT.read_bytes()).hexdigest()=='ad9ace369f9ed2a2c440e1001c18686197e37bbd680ae5ff7e4214a1dc9f9b0d'
 chars=set(chr(i) for i in range(32,127))
 # Extra non-ASCII characters in comments are harmless; keeping a source corpus
 # makes added UI labels enter the baked coverage on regeneration.
 for name in ('main.cpp','core.cpp','runtime.cpp'):
  chars.update(c for c in (ROOT/name).read_text() if ord(c)>127)
 fonts={n:ImageFont.truetype(str(FONT),n,layout_engine=ImageFont.Layout.BASIC) for n in (12,16,24)}
 records=[];blob=bytearray()
 for cp in sorted(map(ord,chars)):
  for n,font in fonts.items():
   ascent,descent=font.getmetrics();mask,(ox,top)=font.getmask2(chr(cp),mode='L',anchor='ls');w,h=mask.size
   assert w<=32 and h<=32,(cp,n,w,h)
   pixels=bytes(mask);encoded=pack(pixels)
   records.append((cp,n,ascent+descent,descent,round(font.getlength(chr(cp))),w,h,ox,-h-top,len(blob),len(encoded)))
   blob.extend(encoded)
 out=['// Generated by tools/build_font.py from PXA Sans SC (Noto Sans CJK/Latin).',
      '// SPDX-License-Identifier: OFL-1.1',
      '// Copyright 2014-2021 Adobe; Copyright 2022 The Noto Project Authors.',
      '// Font notices and OFL licenses: assets/licenses/font-*.txt; font-source/.',
      '#pragma once','#include <cstdint>','namespace md_font {',
      'struct Glyph { uint32_t cp; uint8_t size,line,base,advance,w,h; int8_t ox,oy; uint32_t offset; uint16_t bytes; };',
      'inline constexpr Glyph glyphs[]={']
 out.extend(' {'+','.join(map(str,r))+'},' for r in records);out.append('};')
 out.append('inline constexpr uint8_t data[]={')
 for i in range(0,len(blob),32):out.append(' '+','.join(map(str,blob[i:i+32]))+',')
 out.extend(['};','} // namespace md_font'])
 (ROOT/'font.hpp').write_text('\n'.join(out)+'\n')
 (ROOT/'font-upstream.json').write_text(json.dumps({'font':'PXA Sans SC Regular','license':'OFL-1.1',
  'source':'font-source/noto_sans_cjk_common.ttf','source_sha256':hashlib.sha256(FONT.read_bytes()).hexdigest(),
  'upstream':['https://github.com/notofonts/noto-cjk','https://github.com/notofonts/latin-greek-cyrillic'],
  'generator':'tools/build_font.py','sizes':[12,16,24],'codepoints':len(chars),'glyphs':len(records),'packed_bytes':len(blob)},indent=2)+'\n')
 print(f'Baked {len(records)} glyphs / {len(chars)} characters, {len(blob)} packed bytes; three sizes.')
if __name__=='__main__':main()
